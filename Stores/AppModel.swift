    /// What approving a sign-in gives the app, with live counts. Always Allow
    /// rules already stored for this app are named, because they apply from
    /// its first call: an app that signs in again gets them back.
    func signInConsequence(for request: ApprovalRequest) -> String {
        let summary = toolExposureSummary
        let askingToolIDs = Set(exposedTools.filter(\.asksBeforeRunning).map(\.id))
        let alreadyAllowed = clientToolPermissionSnapshot[request.clientTrustID]?
            .intersection(askingToolIDs).count ?? 0
        var text = "If you approve, \(request.clientName) can run your \(counted(summary.readOnly, "read-only tool")) without asking."
        if fileTransferReachesWholeMac {
            // The one setting that changes what "read-only" can reach, said
            // at the moment the owner decides whom to trust.
            text += " Those tools can read files anywhere on this Mac."
        }
        if alreadyAllowed > 0 {
            text += " \(alreadyAllowed) more already \(alreadyAllowed == 1 ? "has" : "have") Always Allow for this app and will run without asking too."
            let stillAsking = summary.gatedToolCount - alreadyAllowed
            if stillAsking > 0 {
                text += " The other \(stillAsking) will ask first."
            }
        } else if summary.gatedToolCount == 1 {
            text += " The 1 tool marked Asks First will ask before it runs."
        } else if summary.gatedToolCount > 1 {
            text += " The \(summary.gatedToolCount) tools marked Asks First will ask before they run."
        }
        return text
    }

