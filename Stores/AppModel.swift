    func replaceLocalMCPBridgeTools(_ bridgeTools: [ToolDefinition], bridgeIdentity: String?) throws -> Int {
        guard let bridgeIdentity else {
            throw ToolValidationError.invalidMCPBridge("bridge identity is missing")
        }
        for tool in bridgeTools {
            try ToolIdentifier.validate(tool.id)
            try ToolArgumentResolver.validate(tool)
        }

        let incomingIDs = Set(bridgeTools.map(\.id))
        guard incomingIDs.count == bridgeTools.count else {
            throw ToolIdentifierError.duplicate("imported MCP catalog")
        }

        let incomingServerIdentities = Set(bridgeTools.compactMap(\.mcpBridgeServerIdentity))
        let incomingOwnerIdentities = Set(
            bridgeTools.flatMap { $0.mcpBridgeDiscoveryOwners.map(\.serverIdentity) }
        )
        var replacedTools = tools.filter { tool in
            guard tool.isMCPBridge else { return false }
            if let identity = tool.mcpBridgeServerIdentity,
               incomingServerIdentities.contains(identity) {
                return true
            }
            let storedOwners = Set(tool.mcpBridgeDiscoveryOwners.map(\.serverIdentity))
            return !storedOwners.isDisjoint(with: incomingOwnerIdentities)
        }
        if replacedTools.isEmpty {
            // Upgrade-only fallback. A raw command/URL omits environment and
            // header semantics, so it is safe only for one unowned legacy
            // family with the incoming display name. Owned rows never use it.
            let incomingNames = Set(bridgeTools.compactMap { $0.mcpBridgeServerName?.lowercased() })
            let legacyNameMatches = tools.filter {
                $0.isMCPBridge &&
                    $0.mcpBridgeServerIdentity == nil &&
                    incomingNames.contains($0.mcpBridgeServerName?.lowercased() ?? "")
            }
            let legacyFamilies = Set(legacyNameMatches.compactMap(\.mcpBridgeIdentity))
            if legacyFamilies.count == 1,
               legacyFamilies.first == bridgeIdentity {
                replacedTools = legacyNameMatches
            }
        }
        let replacedIDs = Set(replacedTools.map(\.id))
        let nonReplacedIDs = Set(tools.filter { !replacedIDs.contains($0.id) }.map(\.id))
        if let collision = incomingIDs.intersection(nonReplacedIDs).sorted().first {
            throw ToolIdentifierError.duplicate(collision)
        }

        var oldToolsByID = [String: ToolDefinition]()
        var oldDisabledByID = [String: Bool]()
        for tool in replacedTools {
            guard oldToolsByID[tool.id] == nil else {
                throw ToolIdentifierError.duplicate(tool.id)
            }
            oldToolsByID[tool.id] = tool
            oldDisabledByID[tool.id] = disabledToolIDs.contains(tool.id)
        }
        let existingServerWasNotShared = !replacedTools.isEmpty &&
            replacedTools.allSatisfy { disabledToolIDs.contains($0.id) }
        let preparedTools = bridgeTools.map { tool in
            guard let previous = oldToolsByID[tool.id] else { return tool }
            return tool.withPermissionEpoch(previous.permissionEpoch)
        }
        let removedIDs = replacedIDs.subtracting(incomingIDs)

        let originalTools = tools
        let originalDisabledToolIDs = disabledToolIDs
        let originalInvalidToolIDs = invalidSavedToolIDs
        let originalFullDiskAccessPrompt = fullDiskAccessPrompt

        do {
            tools.removeAll { replacedIDs.contains($0.id) }
            for toolID in replacedIDs {
                disabledToolIDs.remove(toolID)
                invalidSavedToolIDs.remove(toolID)
            }
            var relaxedToolNames: [String] = []
            for tool in preparedTools {
                appendTool(tool)
                if let wasDisabled = oldDisabledByID[tool.id] {
                    if wasDisabled {
                        disabledToolIDs.insert(tool.id)
                    } else if oldToolsByID[tool.id]?.asksBeforeRunning == true, !tool.asksBeforeRunning {
                        // The server now calls a tool that asked first
                        // read-only, which would let it run unasked. A server
                        // describes itself, so that is the owner's call.
                        disabledToolIDs.insert(tool.id)
                        relaxedToolNames.append(tool.name)
                    } else {
                        disabledToolIDs.remove(tool.id)
                    }
                } else if existingServerWasNotShared {
                    disabledToolIDs.insert(tool.id)
                }
            }

            try persistUserDefinedTools()
            persistToolExposureState()
            for toolID in removedIDs {
                _ = clientToolPermissionStore.removeToolIDFromAllClients(toolID)
            }
            clientToolPermissionSnapshot = clientToolPermissionStore.snapshot(matching: allTools)
            syncRunningToolSurface()
            if !relaxedToolNames.isEmpty {
                appendLog(
                    level: .warning,
                    "Not Shared until you review: \(relaxedToolNames.sorted().joined(separator: ", ")). The server now describes \(relaxedToolNames.count == 1 ? "it" : "them") as read-only, so \(relaxedToolNames.count == 1 ? "it" : "they") would stop asking first."
                )
            }
            return replacedTools.count
        } catch {
            tools = originalTools
            disabledToolIDs = originalDisabledToolIDs
            invalidSavedToolIDs = originalInvalidToolIDs
            fullDiskAccessPrompt = originalFullDiskAccessPrompt
            throw error
        }
    }

    /// Group toggles must apply the same validation gate as an individual Share
    /// toggle. A missing file that was already shared keeps that state; every
    /// other failing row stays Not Shared.
    private func enableToolsAfterValidation(_ candidateTools: [ToolDefinition]) -> [String] {
        var failures = [String]()
        for tool in candidateTools {
            let wasExposed = isToolExposed(tool)
            do {
                try ToolArgumentResolver.validate(tool)
                disabledToolIDs.remove(tool.id)
                invalidSavedToolIDs.remove(tool.id)
            } catch {
                let isAlreadySharedMissingFile: Bool
                if case ToolValidationError.executableUnavailable(let path) = error,
                   !FileManager.default.fileExists(atPath: path),
                   wasExposed {
                    isAlreadySharedMissingFile = true
                } else {
                    isAlreadySharedMissingFile = false
                }
                if !isAlreadySharedMissingFile {
                    disabledToolIDs.insert(tool.id)
                }
                let message = "Can't share \(tool.name): \(error.localizedDescription)"
                failures.append(message)
                appendLog(level: .warning, message)
            }
        }
        return failures
    }

