    private func revokeOAuthStateForCredential(clientID: String, action: String) {
        let connectedClient = connectedClients.first { $0.id == clientID }
        let summary = authCoordinator.revokeClient(id: clientID)
        // A rotated or deleted credential must not leave that app's queued
        // tool calls waiting on a sign-in that can no longer be proven.
        let deniedRequests = toolCallApprovalCoordinator?.denyPending(
            clientTrustID: connectedClient?.trustID,
            clientID: clientID
        ) ?? 0
        approvals = authCoordinator.approvalSnapshot()
        notifiedAuthorizationRequestIDs.formIntersection(Set(approvals.map(\.id)))
        toolCallApprovals = toolCallApprovalCoordinator?.approvalSnapshot() ?? toolCallApprovals
        setConnectedClients(authCoordinator.connectedClientSnapshot())
        var removedRules = 0
        if let connectedClient {
            removedRules = clientToolPermissionStore.removeClientTrustID(connectedClient.trustID).removedRules
            clientToolPermissionSnapshot = clientToolPermissionStore.snapshot(matching: allTools)
        }
        updateDockBadge()
        appendLog(
            level: .warning,
            "\(action) Revoked \(summary?.accessTokens ?? 0) access tokens, \(summary?.refreshTokens ?? 0) refresh tokens, \(deniedRequests) waiting requests, and \(removedRules) Always Allow rules."
        )
    }

    /// Signs one app out completely (decision D45). Every count in the result
    /// is measured from the revocation itself, never from the view's copy of
    /// the world — the previous version reported a stale token count and
    /// silently left pending tool calls waiting.
    @discardableResult
