    func deployCustomDomainTunnel() {
        guard !cloudflareCustomDomainState.isWorking else {
            appendLog(level: .warning, "Wait for the current Cloudflare operation to finish.")
            return
        }
        guard tunnelStatus.isRunning == false else {
            appendLog(level: .warning, "Stop the current tunnel before deploying a custom domain tunnel.")
            return
        }
        guard let selectedCloudflareZone else {
            cloudflareCustomDomainState = .failed(CloudflareServiceError.zoneRequired.localizedDescription)
            appendLog(level: .warning, "Select a Cloudflare domain before deploying.")
            return
        }
        let subdomain = cloudflareDraft.subdomain
        guard CloudflareService.isValidSubdomain(subdomain.trimmingCharacters(in: .whitespacesAndNewlines)) else {
            let message = CloudflareServiceError.invalidSubdomain.localizedDescription
            cloudflareCustomDomainState = .failed(message)
            appendLog(level: .warning, message)
            return
        }
        let apiToken = cloudflareDraft.trimmedAPIToken
        guard !apiToken.isEmpty else {
            let message = CloudflareServiceError.missingAPIToken.localizedDescription
            cloudflareCustomDomainState = .failed(message)
            appendLog(level: .warning, message)
            return
        }

        cloudflareCustomDomainState = localServerURL == nil ? .preparingLocalServer : .deploying

        Task { [self] in
            do {
                guard let localServerURL = await ensureLocalServerRunning() else {
                    let message: String
                    if case .failed(let detail) = serverStatus {
                        message = detail
                    } else {
                        message = customDomainDeployHint
                    }
                    tunnelStatus = tunnelService.status(localServerURL: self.localServerURL)
                    cloudflareCustomDomainState = .failed(message)
                    appendLog(level: .warning, message)
                    return
                }

                cloudflareCustomDomainState = .deploying
                tunnelStatus = .starting
                appendLog(level: .info, "Deploying Cloudflare custom domain tunnel for \(customCloudflareHostnamePreview ?? selectedCloudflareZone.name).")

                let deployment = try await cloudflareService.deployCustomDomain(
                    zone: selectedCloudflareZone,
                    subdomain: subdomain,
                    localServerURL: localServerURL,
                    apiToken: apiToken,
                    // Serve the MacRemote favicon at the zone apex (via a
                    // scoped Worker) so Claude.ai's connector icon resolves.
                    // Best-effort: skipped if the apex already has a favicon.
                    provisionApexFavicon: true
                )
                lastCloudflareDeployment = deployment
                if let apexFavicon = deployment.apexFavicon {
                    appendLog(level: apexFavicon.isFailure ? .warning : .info, apexFavicon.logMessage)
                }
                try tunnelService.startNamedTunnel(deployment: deployment) { [weak self] event in
                    Task { @MainActor in
                        self?.handleTunnelEvent(event)
                    }
                }
                cloudflareCustomDomainState = .deployed(deployment.hostname)
                appendLog(
                    level: .info,
                    "Deployed Cloudflare custom domain tunnel for \(deployment.hostname) with \(connectorAuthMode.protectionTitle) sign-in."
                )
                if let legacyAccessCleanup = deployment.legacyAccessCleanup {
                    appendLog(level: .warning, legacyAccessCleanup)
                }
            } catch {
                let message = error.localizedDescription
                tunnelStatus = tunnelService.status(localServerURL: localServerURL)
                cloudflareCustomDomainState = .failed(message)
                appendLog(level: .error, "Cloudflare custom domain deploy failed: \(message)")
            }
        }
    }

    func checkSmokeReadiness() {
        guard !smokeTestState.isRunning else {
            appendLog(level: .warning, "Wait for the current test before checking readiness again.")
            return
        }

        anthropicCredentialState = .checking
        appendLog(level: .info, "Checking test readiness.")

        Task {
            let fdaRequired = exposedToolsRequireFullDiskAccess
            let fdaReport = fdaRequired ? await refreshFullDiskAccessStatus() : fullDiskAccessReport
            let fdaReady = !fdaRequired || fdaReport.isReady
            let privacyRequired = exposedToolsRequireCheckedMacOSPrivacyAccess
            let privacyReport = privacyRequired ? await refreshMacOSPrivacyAccessStatus() : macOSPrivacyAccessReport
            let privacyReady = !privacyRequired || privacyReport.isReady
            let credentialState = await smokeTestService.checkAnthropicAPIKey(environment: AppModel.toolEnvironment)
            anthropicCredentialState = credentialState

            let fdaMessage = fdaReady ? "Full Disk Access ready" : "Full Disk Access not ready"
            let privacyMessage = privacyReady ? "macOS privacy ready" : "macOS privacy not ready"
            let credentialMessage = credentialState.isReady ? "Anthropic key ready" : "Anthropic key not ready"
            if fdaRequired, !fdaReport.isReady {
                presentFullDiskAccessPrompt(reason: .remoteProof)
            }
            if privacyRequired, !privacyReport.isReady {
                revealReadinessRow(.privacyPermissions)
            }
            appendLog(
                level: credentialState.isReady && fdaReady && privacyReady ? .info : .warning,
                "\(fdaMessage); \(privacyMessage); \(credentialMessage)."
            )
        }
    }

    func runSmokeTest(mode: SmokeTestMode) {
        guard let mcpURL = currentPublicMCPURL else {
            appendLog(level: .warning, "Create a public MCP URL before running the \(mode.logTitle).")
            return
        }

        let readiness = smokeReadiness
        let canRun = mode == .preflight ? readiness.canRunPreflight : readiness.canRunAnthropicAPI
        guard canRun else {
            appendLog(level: .warning, "\(mode.logTitle) blocked: \(readiness.blockingDetails.first ?? "check readiness first").")
            return
        }

        guard !smokeTestState.isRunning else {
            appendLog(level: .warning, "A test is already running.")
            return
        }

        smokeTestState = .running(mode)
        appendLog(level: .info, "Started \(mode.logTitle).")
        let toolSurface = smokeProofToolSurfaceDescription
        let mcpURLString = mcpURL.absoluteString
        let smokeToolID = smokeToolID(for: mode)

        Task {
            do {
                let result = try await smokeTestService.run(
                    mode: mode,
                    mcpURL: mcpURL,
                    toolID: smokeToolID,
                    environment: AppModel.toolEnvironment
                )

                if result.succeeded {
                    smokeTestState = .passed(mode, "\(result.summary) in \(result.duration.formattedDuration).")
                    appendLog(level: .info, "\(mode.logTitle) passed in \(result.duration.formattedDuration).")
                } else {
                    smokeTestState = .failed(mode, result.summary)
                    appendLog(level: .warning, "\(mode.logTitle) failed: \(result.summary)")
                }
                lastSmokeProof = SmokeProofRecord(
                    date: Date(),
                    mode: mode,
                    mcpURL: mcpURLString,
                    toolSurface: toolSurface,
                    succeeded: result.succeeded,
                    resultSummary: result.summary,
                    exitCode: result.processResult.exitCode,
                    duration: result.duration,
                    markers: SmokeTestService.proofMarkers(for: result.processResult)
                )
            } catch {
                let message = error.localizedDescription
                smokeTestState = .failed(mode, message)
                lastSmokeProof = SmokeProofRecord(
                    date: Date(),
                    mode: mode,
                    mcpURL: mcpURLString,
                    toolSurface: toolSurface,
                    succeeded: false,
                    resultSummary: message,
                    exitCode: nil,
                    duration: nil,
                    markers: []
                )
                appendLog(level: .error, "\(mode.logTitle) failed: \(message)")
            }
        }
    }

