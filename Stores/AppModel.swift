    /// True when the owner chose Your Domain as this Mac's public address.
    /// The Address card stores the choice under this key.
    private var prefersCustomDomain: Bool {
        userDefaults.string(forKey: "MacRemote.addressMode") == "yourDomain"
    }

    /// "Go Public" means "use the address I chose". With Your Domain chosen it
    /// must not start an Instant Link: that would hand out a random address
    /// while the owner's own stays dead. A domain that is already deployed
    /// goes public again by itself (`resumableCustomDomain`). Any other must
    /// be deployed from the Address card, so this sends the owner there.
    /// Returns true when it did.
    private func routeGoPublicToCustomDomainIfChosen() -> Bool {
        guard prefersCustomDomain, resumableCustomDomain == nil else { return false }
        if savedCloudflareDomain?.isChosen(by: cloudflareDraft) != true {
            // No deployed domain is chosen, so no key for one may remain.
            cloudflareRunTokenStore.delete()
        }
        appendLog(level: .info, "Your Domain is this Mac's public address. Deploy it from Address to go public.")
        requestConnectionAddressSetup()
        return true
    }

    /// The deployed Your Domain, when it can go public again without
    /// Cloudflare credentials: the owner still has it chosen, its run token
    /// is in the Keychain, and the local server is on the port Cloudflare
    /// sends this tunnel's requests to. Anything else needs a deploy, the
    /// only step that uses the API token or Wrangler.
    private var resumableCustomDomain: CloudflareCustomDomainDeployment? {
        guard let saved = savedCloudflareDomain,
              saved.isChosen(by: cloudflareDraft),
              let localPort = saved.localPort,
              localPort == localServerURL?.port,
              let token = cloudflareRunTokenStore.token(forTunnelID: saved.tunnelID) else {
            return nil
        }
        return CloudflareCustomDomainDeployment(saved: saved, tunnelToken: token)
    }

    /// The hostname of the deployed Your Domain while the owner still has it
    /// chosen. The Address card uses it to say the domain is deployed before
    /// this launch has brought it up.
    var chosenDeployedHostname: String? {
        guard let saved = savedCloudflareDomain, saved.isChosen(by: cloudflareDraft) else { return nil }
        return saved.hostname
    }

    /// The saved run token belongs to the deployed domain. Once the owner
    /// points the form at another address it is deleted, so the secret never
    /// outlives the choice it was saved for.
    private func deleteRunTokenIfDomainChanged(from oldDraft: CloudflareCustomDomainDraft) {
        guard let saved = savedCloudflareDomain,
              saved.isChosen(by: oldDraft),
              !saved.isChosen(by: cloudflareDraft) else {
            return
        }
        cloudflareRunTokenStore.delete()
    }

    /// Brings a deployed Your Domain back up from its saved run token.
    /// Nothing on Cloudflare's side is read or changed, so no API token and
    /// no Wrangler are involved.
    private func startSavedCustomDomain(localServerURL: URL) {
        guard let deployment = resumableCustomDomain else { return }
        tunnelStatus = .starting
        lastCloudflareDeployment = deployment
        activeTunnelMode = .named(deployment, fromSavedToken: true)
        tunnelWatchdog.activate(localServerURL: localServerURL)
        do {
            try tunnelService.startNamedTunnel(deployment: deployment) { [weak self] event in
                Task { @MainActor in
                    self?.handleTunnelEvent(event)
                }
            }
            appendLog(level: .info, "Starting \(deployment.hostname) with its saved key.")
        } catch {
            let message = error.localizedDescription
            deactivateTunnelWatchdog()
            tunnelStatus = .failed(message)
            appendLog(level: .error, "Cloudflare Tunnel failed to start: \(message)")
        }
    }

    func startTunnel() {
        // Already public, or on the way: a second start would fail and mark a
        // link that then comes up as failed.
        guard !tunnelStatus.isRunning, !tunnelStatus.isRecovering,
              !cloudflareCustomDomainState.isWorking else { return }
        guard !routeGoPublicToCustomDomainIfChosen() else { return }
        guard let localServerURL else {
            tunnelStatus = .stopped
            appendLog(level: .warning, "Start the local server before going public.")
            return
        }
        guard !prefersCustomDomain else {
            // Not sent to the Address card above, so the deployed domain can
            // go public again by itself.
            startSavedCustomDomain(localServerURL: localServerURL)
            return
        }

        tunnelStatus = .starting
        activeTunnelMode = .quick
        tunnelWatchdog.activate(localServerURL: localServerURL)
        do {
            try tunnelService.startQuickTunnel(localServerURL: localServerURL) { [weak self] event in
                Task { @MainActor in
                    self?.handleTunnelEvent(event)
                }
            }
            appendLog(level: .info, "Starting Cloudflare Tunnel for \(localServerURL.absoluteString).")
        } catch {
            let message = error.localizedDescription
            deactivateTunnelWatchdog()
            tunnelStatus = .failed(message)
            appendLog(level: .error, "Cloudflare Tunnel failed to start: \(message)")
        }
    }

    func stopTunnel() {
        deactivateTunnelWatchdog()
        clearTunnelSupervision()
        tunnelService.stop()
        tunnelStatus = localServerURL == nil ? .stopped : .ready
        appendLog(level: .info, "Cloudflare Tunnel stopped.")
    }

    func refreshCloudflareDomains() {
        guard !cloudflareCustomDomainState.isWorking else {
            appendLog(level: .warning, "Wait for the current Cloudflare operation to finish.")
            return
        }
        guard canLoadCloudflareDomains else {
            let message = CloudflareServiceError.wranglerUnavailable.localizedDescription
            cloudflareCustomDomainState = .failed(.loadingDomains(message: message))
            appendLog(level: .warning, message)
            return
        }

        cloudflareCustomDomainState = .loadingDomains
        appendLog(
            level: .info,
            cloudflareDraft.trimmedAPIToken.isEmpty
                ? "Loading Cloudflare domains with Wrangler."
                : "Loading Cloudflare domains with the session-only API token."
        )

        Task {
            do {
                let zones = try await cloudflareService.loadZones(apiToken: cloudflareDraft.trimmedAPIToken)
                applyLoadedCloudflareZones(zones)
                if let message = cloudflareCustomDomainState.domainLoadFailureMessage {
                    appendLog(level: .warning, message)
                } else {
                    appendLog(level: .info, "Loaded \(zones.count) Cloudflare domain\(zones.count == 1 ? "" : "s").")
                }
            } catch {
                let failure = Self.cloudflareFailurePresentation(
                    for: error,
                    stage: nil,
                    apiToken: cloudflareDraft.trimmedAPIToken
                )
                cloudflareZones = []
                cloudflareDraft.selectedZoneID = nil
                cloudflareCustomDomainState = .failed(.loadingDomains(
                    message: failure.message,
                    technicalDetail: failure.technicalDetail
                ))
                appendLog(level: .error, "Cloudflare domains failed to load: \(failure.technicalDetail ?? failure.message)")
            }
        }
    }

    /// Applies one completed domain lookup without silently choosing a write
    /// target. A previous choice survives only while it remains in the result.
    func applyLoadedCloudflareZones(_ zones: [CloudflareZone]) {
        cloudflareZones = zones
        guard !zones.isEmpty else {
            cloudflareDraft.selectedZoneID = nil
            cloudflareCustomDomainState = .failed(.loadingDomains(
                message: "No Cloudflare domains were found. Add a domain to Cloudflare, then choose Load Domains again."
            ))
            return
        }
        if let selectedZoneID = cloudflareDraft.selectedZoneID,
           zones.contains(where: { $0.id == selectedZoneID }) {
            // Keep the user's explicit selection.
        } else {
            cloudflareDraft.selectedZoneID = nil
        }
        cloudflareCustomDomainState = .ready
    }

