    /// Changes the sign-in method. Returns the sentence Settings shows about
    /// what the change signed out, or nil when it stopped nothing.
    @discardableResult
    func setConnectorAuthMode(_ mode: ConnectorAuthMode) -> String? {
        let previous = connectorAuthMode
        if mode.requiresOAuthClientSecret, oauthClientCredentials.isEmpty {
            generateOAuthClientCredentials()
        }
        if mode == .singleHeaderToken, connectorHeaderToken == nil {
            generateConnectorHeaderToken()
        }
        connectorAuthMode = mode
        persistConnectorSettings()
        authCoordinator.updateClientAuthentication(currentOAuthClientAuthenticationPolicy)
        syncConnectorHeaderToken()
        guard previous != mode else { return nil }
        appendLog(
            level: .info,
            "Sign-in method changed from \(previous.title) to \(mode.title)."
        )
        return signOutOtherSignInMethods(leaving: previous)
    }

    /// How many connected apps a change to `mode` would sign out. Settings
    /// asks before making a change that signs anything out: one slip of the
    /// picker would otherwise disconnect every app, with no way back short of
    /// approving each one again on this Mac.
    func connectedAppsSignedOut(bySwitchingTo mode: ConnectorAuthMode) -> Int {
        guard mode != connectorAuthMode else { return 0 }
        let listedClientIDs = Set(authCoordinator.connectedClientSnapshot().map(\.id))
        return authCoordinator.clientIdentities().count { identity in
            guard listedClientIDs.contains(identity.clientID) else { return false }
            switch mode {
            case .macRemoteOAuthOnly: return identity.usesOwnerCredentials
            case .oauthClientSecret: return !identity.usesOwnerCredentials
            case .singleHeaderToken: return true
            }
        }
    }

    /// One sign-in method is accepted at a time. Changing it ends what the
    /// others let in: every app the new method does not admit is signed out
    /// with its tokens, waiting requests, and Always Allow settings, and the
    /// Single Header token stops working when the owner leaves that method.
    /// Without this, an app admitted under the old method stayed signed in
    /// and kept renewing. Returns the sentence for Settings, or nil.
    private func signOutOtherSignInMethods(leaving previous: ConnectorAuthMode) -> String? {
        var sentences: [String] = []
        if previous == .singleHeaderToken, connectorHeaderToken != nil {
            sentences.append("The Single Header token no longer works.")
        }

        // Which apps the new method does not admit, and how to name them.
        let stopped: [(clientID: String, trustID: String, usesOwnerCredentials: Bool)]
        let one: String
        let many: String
        let identities = authCoordinator.clientIdentities()
        switch connectorAuthMode {
        case .macRemoteOAuthOnly:
            stopped = identities.filter(\.usesOwnerCredentials)
            one = "1 app that used a client ID and secret"
            many = "apps that used a client ID and secret"
        case .oauthClientSecret:
            stopped = identities.filter { !$0.usesOwnerCredentials }
            one = "1 app that signed itself up"
            many = "apps that signed themselves up"
        case .singleHeaderToken:
            stopped = identities
            one = "1 app"
            many = "apps"
        }

        // A client the owner never let in is removed as well, but it was
        // never an app in the Apps list, so the report does not count it.
        let listedClientIDs = Set(authCoordinator.connectedClientSnapshot().map(\.id))
        var signedOut = 0
        var removed = (registrations: 0, signIns: 0, accessTokens: 0, refreshTokens: 0, requests: 0, rules: 0)
        for identity in stopped {
            let summary = authCoordinator.revokeClient(id: identity.clientID)
            let deniedRequests = toolCallApprovalCoordinator?.denyPending(
                clientTrustID: identity.trustID,
                clientID: identity.clientID
            ) ?? 0
            let removedRules = clientToolPermissionStore.removeClientTrustID(identity.trustID).removedRules
            guard let summary, listedClientIDs.contains(identity.clientID) else { continue }
            signedOut += 1
            removed.registrations += summary.clients
            removed.signIns += summary.authorizations
            removed.accessTokens += summary.accessTokens
            removed.refreshTokens += summary.refreshTokens
            removed.requests += deniedRequests
            removed.rules += removedRules
        }
        if !stopped.isEmpty {
            approvals = authCoordinator.approvalSnapshot()
            notifiedAuthorizationRequestIDs.formIntersection(Set(approvals.map(\.id)))
            toolCallApprovals = toolCallApprovalCoordinator?.approvalSnapshot() ?? toolCallApprovals
            notifiedToolCallRequestIDs.formIntersection(Set(toolCallApprovals.map(\.id)))
            setConnectedClients(authCoordinator.connectedClientSnapshot())
            updateDockBadge()
        }
        if signedOut > 0 {
            sentences.append(ConnectedAppSignOutResult(
                appName: signedOut == 1 ? one : "\(signedOut) \(many)",
                registrations: removed.registrations,
                authorizations: removed.signIns,
                accessTokens: removed.accessTokens,
                refreshTokens: removed.refreshTokens,
                pendingRequests: removed.requests,
                alwaysAllowRules: removed.rules
            ).summary)
        }

        guard !sentences.isEmpty else { return nil }
        let summary = sentences.joined(separator: " ")
        appendLog(level: .warning, "\(summary) \(connectorAuthMode.title) is now the only way to sign in.")
        return summary
    }

