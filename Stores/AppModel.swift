    init(
        userDefaults: UserDefaults = .standard,
        toolStore: ToolRegistryStore = ToolRegistryStore(),
        oauthGrantStore: OAuthGrantStore? = nil,
        oauthClientCredentialStore: OAuthClientCredentialStore? = nil,
        connectorHeaderTokenStore: OAuthClientCredentialStore? = nil,
        localMCPScanner: LocalMCPScanner = LocalMCPScanner(),
        upstreamOAuthStore: MCPUpstreamOAuthStore = .shared,
        upstreamOAuthClient: MCPUpstreamOAuthClient? = nil,
        cliScanner: LocalCLIScanner = LocalCLIScanner(),
        provenanceInspector: any ToolProvenanceInspecting = SecStaticCodeProvenanceInspector(),
        cloudflaredManager: CloudflaredManager? = nil,
        cloudflareRunTokenStore: CloudflareRunTokenStore? = nil,
        helperTetherExecutableURL: URL? = nil,
        runsLaunchActions: Bool = false
    ) {
        self.userDefaults = userDefaults
        self.fileTransferFolders = FileTransferPathPolicy(userDefaults: userDefaults).allowedFolders
        self.resultCardPreferences = ResultCardPreferences(userDefaults: userDefaults)
        self.toolStore = toolStore
        // The helper manager owns cloudflared resolution for the whole app, so
        // it is built before anything that can launch or look for the helper.
        let helperManager = cloudflaredManager ?? CloudflaredManager()
        self.cloudflaredManager = helperManager
        // Status stays cheap so a refresh never hashes 40 MB on the main actor;
        // a launch proves the bytes first, and a pinned session copy is
        // re-proven rather than swapped.
        self.tunnelService = TunnelService(
            resolver: TunnelService.CloudflaredResolver(
                status: { helperManager.cachedExecutablePath() },
                launch: { helperManager.resolvedExecutablePath() },
                verify: { helperManager.verifyLaunchPath($0) }
            ),
            childRecordURL: toolStore.fileURL
                .deletingLastPathComponent()
                .appendingPathComponent("tunnel-helper.json"),
            tetherExecutableURL: helperTetherExecutableURL
        )
        self.cloudflareService = CloudflareService(executablePath: { name in
            name == "cloudflared"
                ? helperManager.resolvedExecutablePath()
                : ExecutableLocator.executablePath(named: name)
        })
        self.cloudflareRunTokenStore = cloudflareRunTokenStore ?? CloudflareRunTokenStore()
        self.oauthGrantStore = oauthGrantStore ?? OAuthGrantStore(userDefaults: userDefaults)
        self.oauthClientCredentialStore = oauthClientCredentialStore ?? OAuthClientCredentialStore(userDefaults: userDefaults)
        self.connectorHeaderTokenStore = connectorHeaderTokenStore ?? OAuthClientCredentialStore(
            userDefaults: userDefaults,
            service: "com.macstories.MacRemote.connectorHeaderToken"
        )
        self.clientToolPermissionStore = ClientToolPermissionStore(userDefaults: userDefaults)
        self.approvalDecisionLog = ApprovalDecisionLog(
            fileURL: toolStore.fileURL
                .deletingLastPathComponent()
                .appendingPathComponent("approval-decisions.json")
        )
        self.toolSurfaceRuntime = ToolSurfaceRuntime(
            environment: Self.toolEnvironment,
            artifactStore: artifactStore
        )
        self.localMCPScanner = localMCPScanner
        self.upstreamOAuthStore = upstreamOAuthStore
        self.upstreamOAuth = upstreamOAuthClient ?? MCPUpstreamOAuthClient(
            store: upstreamOAuthStore,
            openURL: { url in
                await MainActor.run { _ = NSWorkspace.shared.open(url) }
            }
        )
        self.cliScanner = cliScanner
        self.provenanceInspector = provenanceInspector
        self.hasCompletedWelcome = userDefaults.bool(forKey: Self.hasCompletedWelcomeKey)
        self.isMenuBarExtraEnabled = Self.loadBool(Self.menuBarExtraEnabledKey, from: userDefaults, defaultValue: true)
        self.warnBeforeQuitWhileSharing = Self.loadBool(Self.warnBeforeQuitWhileSharingKey, from: userDefaults, defaultValue: true)
        self.isSetupChecklistEnabled = Self.loadBool(Self.setupChecklistEnabledKey, from: userDefaults, defaultValue: true)
        self.goPublicAtLaunchHostname = userDefaults.string(forKey: Self.goPublicAtLaunchHostnameKey)
        // Non-interactive: a Keychain prompt here (e.g. after a re-signed rebuild)
        // would block the app before its first window. Locked entries surface in
        // Settings › Security with a user-initiated Unlock instead.
        let loadedCredentials = self.oauthClientCredentialStore.loadAllDetailed(interactive: false)
        self.oauthClientCredentials = loadedCredentials.credentials
        self.lockedOAuthClientIDs = loadedCredentials.lockedClientIDs
        self.connectorHeaderToken = self.connectorHeaderTokenStore.loadAllDetailed(interactive: false).credentials.first
        self.connectorProvider = Self.loadConnectorProvider(from: userDefaults)
        // D42 — a fresh install lands on the product default, never on
        // something derived from the selected app. Retired raw values still
        // migrate inside `from(persistedRawValue:)`; nothing is rewritten here.
        self.connectorAuthMode = Self.loadConnectorAuthMode(from: userDefaults) ?? .productDefault
        self.oauthAccessTokenTTLSeconds = Self.loadOAuthAccessTokenTTLSeconds(from: userDefaults)
        self.oauthRefreshTokenTTLSeconds = Self.loadOAuthRefreshTokenTTLSeconds(from: userDefaults)
        let cloudflarePreferences = CloudflareCustomDomainPreferences.load(from: userDefaults)
        self.cloudflareDraft = cloudflarePreferences.draft
        self.savedCloudflareDomain = cloudflarePreferences.deployment
        self.instanceID = AppModel.makeInstanceID(userDefaults: userDefaults)
        var persistedDisabledToolIDs = Set(userDefaults.stringArray(forKey: Self.disabledToolIDsKey) ?? [])
        var seenBuiltInToolIDs = Set(userDefaults.stringArray(forKey: Self.seenBuiltInFileTransferToolIDsKey) ?? [])

        var loadedTools: [ToolDefinition]
        let toolLoadIssues: [ToolRegistryLoadIssue]
        var startupError: String?
        var toolRegistryWriteBlockReason: String?
        do {
            let report = try toolStore.loadUserDefinedToolsReport()
            loadedTools = report.tools
            toolLoadIssues = report.issues
            startupError = nil
            let unreadableCount = report.issues.count(where: \.blocksWrites)
            toolRegistryWriteBlockReason = report.writesAllowed ? nil :
                "\(unreadableCount) saved tool row\(unreadableCount == 1 ? "" : "s") could not be decoded."
        } catch {
            loadedTools = []
            toolLoadIssues = []
            startupError = "Could not load saved tools: \(error.localizedDescription) Catalog changes are blocked to preserve tools.json."
            toolRegistryWriteBlockReason = "The saved tool registry could not be read: \(error.localizedDescription)"
        }

        let catalogTools = FileTransferToolCatalog.builtInTools
        // Fail closed for every invalid or ambiguous identity without
        // rewriting the user's file; valid, unrelated rows remain usable.
        let identityGroups = Dictionary(grouping: catalogTools + loadedTools, by: \.id)
        var unsafeToolIDs = Set(identityGroups.compactMap { id, matchingTools in
            !ToolIdentifier.isValid(id) || matchingTools.count > 1 ? id : nil
        })
        if toolRegistryWriteBlockReason == nil, !unsafeToolIDs.isEmpty {
            let detail = "Saved tools contain duplicate or invalid IDs: \(unsafeToolIDs.sorted().joined(separator: ", "))."
            startupError = "\(detail) Those tools stay Not Shared, and catalog changes are blocked to preserve tools.json."
            toolRegistryWriteBlockReason = detail
        }
        // A row that could not be decoded may still claim the same raw ID as a
        // decoded row. Do not expose that ambiguous identity while preserving
        // every byte for manual recovery.
        unsafeToolIDs.formUnion(toolLoadIssues.filter(\.blocksWrites).compactMap(\.toolID))
        persistedDisabledToolIDs.formUnion(unsafeToolIDs)

        let allToolIDs = Set(loadedTools.map(\.id)).union(catalogTools.map(\.id))
        var disabledToolIDs = persistedDisabledToolIDs.intersection(allToolIDs)
        let invalidToolIDs = Set(toolLoadIssues.compactMap(\.toolID))
        let quarantinedToolIDs = Set(
            toolLoadIssues.filter(\.requiresQuarantine).compactMap(\.toolID)
        )
        disabledToolIDs.formUnion(quarantinedToolIDs)

        // Sharing is tied to the exact tool the owner last saw in this app. A
        // row that appears or changes in the saved tools file any other way (a
        // hand edit, another program, a file copied from another Mac) starts
        // Not Shared. So does every tool when the preferences that record
        // sharing are gone, because the "Not Shared" list went with them.
        let knownToolFingerprints = userDefaults.dictionary(forKey: Self.knownToolFingerprintsKey) as? [String: String]
        // The first launch of a version with this check adopts what is there.
        let adoptsExistingTools = knownToolFingerprints == nil
            && userDefaults.object(forKey: Self.seenBuiltInFileTransferToolIDsKey) != nil
        let toolsChangedOutsideApp = adoptsExistingTools ? [] : loadedTools.filter {
            knownToolFingerprints?[$0.id] != $0.securityFingerprint && !disabledToolIDs.contains($0.id)
        }
        disabledToolIDs.formUnion(toolsChangedOutsideApp.map(\.id))

        // MacRemote 1.0 offered Git Status and Git Log as read-only tools,
        // which run without asking. Git runs programs named in the settings of
        // whatever folder it is pointed at, so on an install that still has
        // them they ask first from now on. Done once: the owner may set them
        // back in Tools, and that choice is theirs to keep.
        var gitToolsNowAsking: [String] = []
        if !userDefaults.bool(forKey: Self.gitPresetToolsAskFirstKey) {
            userDefaults.set(true, forKey: Self.gitPresetToolsAskFirstKey)
            loadedTools = loadedTools.map { tool in
                guard Self.isUnaskedGitPresetTool(tool) else { return tool }
                gitToolsNowAsking.append(tool.name)
                return tool.withCapability(.write)
            }
        }
        userDefaults.set(Self.fingerprintsByToolID(loadedTools), forKey: Self.knownToolFingerprintsKey)

        for tool in catalogTools where !seenBuiltInToolIDs.contains(tool.id) {
            disabledToolIDs.insert(tool.id)
            seenBuiltInToolIDs.insert(tool.id)
        }
        userDefaults.set(seenBuiltInToolIDs.sorted(), forKey: Self.seenBuiltInFileTransferToolIDsKey)
        if disabledToolIDs != persistedDisabledToolIDs.intersection(allToolIDs) {
            userDefaults.set(disabledToolIDs.sorted(), forKey: Self.disabledToolIDsKey)
        }

        self.tools = loadedTools
        self.disabledToolIDs = disabledToolIDs
        self.invalidSavedToolIDs = invalidToolIDs
        self.toolRegistryWriteBlockReason = toolRegistryWriteBlockReason
        // Left behind by Background Tasks, which was removed after 1.0.1.
        // Nothing reads them any more.
        for leftover in ["Tasks", "task-execution-preferences.json"] {
            try? FileManager.default.removeItem(
                at: toolStore.fileURL.deletingLastPathComponent().appendingPathComponent(leftover)
            )
        }
        let cliScanCacheURL = toolStore.fileURL
            .deletingLastPathComponent()
            .appendingPathComponent("cli-scan-cache.json")
        let restoredCLIScanCache = Self.loadCLIScanCache(at: cliScanCacheURL)
        self.cliScanCacheURL = cliScanCacheURL
        self.cliScanCache = restoredCLIScanCache
        if let restoredCLIScanCache {
            self.cliScanState = restoredCLIScanCache.restoredState
        }
        let mcpScanCacheURL = toolStore.fileURL
            .deletingLastPathComponent()
            .appendingPathComponent("mcp-scan-cache.json")
        self.mcpScanCacheURL = mcpScanCacheURL
        self.mcpScanCache = Self.loadMCPScanCache(at: mcpScanCacheURL)
        self.clientToolPermissionSnapshot = clientToolPermissionStore.snapshot(
            matching: catalogTools + loadedTools
        )
        self.toolSurfaceRuntime.update(tools: Self.exposedTools(from: loadedTools, builtInCatalogTools: catalogTools, disabledToolIDs: disabledToolIDs))
        // R16 — remote pre-execution revalidation: a changed binary identity
        // blocks the call (and auto-unshares the tool) before anything runs.
        self.toolSurfaceRuntime.setPreExecutionCheck { [weak self] tool in
            guard let self else { return }
            if case .identityChanged = await self.revalidateToolProvenance(toolID: tool.id) {
                throw ToolValidationError.identityChanged(tool.name)
            }
        }

        installApprovalCoordinators()
        tunnelStatus = tunnelService.status(localServerURL: nil)
        if let startupError {
            logs.insert(AppLogEntry(date: Date(), level: .error, message: startupError), at: 0)
        }
        // A row written by hand may lack the permission stamp the app adds, and
        // gets a new one on every load. Saving here keeps the stamp, and with
        // it the row's fingerprint, the same from one launch to the next.
        if adoptsExistingTools || !toolsChangedOutsideApp.isEmpty || !gitToolsNowAsking.isEmpty {
            try? persistUserDefinedTools()
        }
        if !gitToolsNowAsking.isEmpty {
            logs.insert(
                AppLogEntry(
                    date: Date(),
                    level: .warning,
                    message: "\(gitToolsNowAsking.sorted().joined(separator: " and ")) now ask\(gitToolsNowAsking.count == 1 ? "s" : "") before running: Git can run programs named in a folder's settings. Use Always Allow for an app you trust."
                ),
                at: 0
            )
        }
        if !toolsChangedOutsideApp.isEmpty {
            let names = toolsChangedOutsideApp.map(\.name).sorted().prefix(5).joined(separator: ", ")
            let count = toolsChangedOutsideApp.count
            logs.insert(
                AppLogEntry(
                    date: Date(),
                    level: .warning,
                    message: "\(count) tool\(count == 1 ? " was" : "s were") added or changed outside MacRemote and \(count == 1 ? "is" : "are") now Not Shared until you review \(count == 1 ? "it" : "them") in Tools: \(names)\(count > 5 ? ", and more" : "")."
                ),
                at: 0
            )
        }
        for issue in toolLoadIssues {
            let message: String
            switch issue.problem {
            case .validation(.executableUnavailable(let path)):
                message = "\(issue.toolName): executable no longer found at \(path)"
            case .validation(let error):
                message = "Kept saved tool \(issue.toolName) Not Shared: \(error.localizedDescription)"
            case .decoding(let row, let reason):
                message = "Could not read saved tool \(issue.toolName) at row \(row): \(reason). Catalog changes are blocked to preserve tools.json."
            case .unexpectedValidation(let reason):
                message = "Kept saved tool \(issue.toolName) Not Shared after an unexpected validation failure: \(reason)"
            }
            logs.insert(
                AppLogEntry(
                    date: Date(),
                    level: .warning,
                    message: message
                ),
                at: 0
            )
        }
        appendLog(
            level: .info,
            "MacRemote initialized with \(toolExposureSummary.total) shared tools."
        )
        if tunnelService.stopHelperLeftByPreviousLaunch() {
            appendLog(level: .warning, "Stopped a public link that was still running from a previous launch.")
        }
        warnIfTunnelSupervisionWasInterrupted()
        configureUserNotificationsIfSupported()
        if userDefaults.bool(forKey: Self.fullDiskAccessRelaunchPendingKey) {
            userDefaults.removeObject(forKey: Self.fullDiskAccessRelaunchPendingKey)
            hasAutoRelaunchedForFullDiskAccess = true
            Task { await completeFullDiskAccessRelaunch() }
        }
        if hasLockedOAuthCredentials {
            appendLog(
                level: .warning,
                "Saved sign-in credentials are locked by macOS. Unlock them in Settings › Security so connected apps can keep signing in."
            )
        }
        tunnelWatchdog = Self.makeTunnelWatchdog(
            for: self,
            tunnelService: tunnelService,
            cloudflaredManager: self.cloudflaredManager,
            originHealthChecker: originHealthChecker
        )
        self.cloudflaredManager.setTunnelRunningCheck { [weak self] in
            self?.tunnelService.isProcessRunning() ?? false
        }
        self.cloudflaredManager.onLog = { [weak self] level, message in
            self?.appendLog(level: level, message)
        }
        self.cloudflaredManager.onInstalled = { [weak self] in
            self?.handleCloudflaredHelperInstalled()
        }
        self.cloudflaredManager.onResolved = { [weak self] in
            // The status path answers cheaply while verification runs off the
            // main actor; this is where the proven answer lands.
            self?.refreshTunnelStatus()
        }
        self.cloudflaredManager.refresh()
        // Only the app passes this. A window may never open at login, so the
        // launch work cannot wait for one.
        if runsLaunchActions {
            Task { await goPublicAtLaunchIfEnabled() }
        }
    }

