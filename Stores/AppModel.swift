    /// Reconcile a catalog scope in one transaction: refresh retained IDs, add
    /// newly cataloged tools, and retire obsolete Federico-owned IDs when the
    /// complete provider scope is being updated.
    func updateUserToolsFromCatalog(
        _ presets: [DefaultToolPreset] = DefaultToolPresetCatalog.presets,
        sourceName: String = "Catalog"
    ) -> String? {
        let index = installationIndex
        let updateCandidates = index.updateablePresets(in: presets)
        let scanAdoptions = adoptableScannedTools(
            in: presets,
            installationIndex: index
        )
        let addCandidates = index.installablePresets(in: presets)
        let retiredIDs = retiredFedericoToolIDs(for: presets)
        guard !updateCandidates.isEmpty || !scanAdoptions.isEmpty ||
                !addCandidates.isEmpty || !retiredIDs.isEmpty else {
            appendLog(level: .info, "\(sourceName) is already up to date.")
            return nil
        }

        let originalTools = tools
        let originalDisabledToolIDs = disabledToolIDs
        let originalAllowances = clientToolPermissionSnapshot
        let originalInvalidToolIDs = invalidSavedToolIDs
        let originalFullDiskAccessPrompt = fullDiskAccessPrompt
        let originalIdentityChangedToolIDs = provenanceIdentityChangedToolIDs
        let originalProvenanceContentUpdates = provenanceContentUpdates

        do {
            var updatedNames: [String] = []
            for preset in updateCandidates {
                guard let index = tools.firstIndex(where: {
                    $0.id == preset.toolID && $0.isUserDefined && $0.mcpBridgeIdentity == nil
                }) else {
                    throw ToolValidationError.invalidArgument(
                        "Catalog tool \(preset.name) is no longer available to update."
                    )
                }
                let existing = tools[index]
                let updated = try preset.draft.makeTool(
                    id: existing.id,
                    permissionEpoch: existing.permissionEpoch
                )
                tools[index] = updated
                invalidSavedToolIDs.remove(existing.id)
                updatedNames.append(updated.name)

                if isToolExposed(updated),
                   serverStatus.isRunning,
                   updated.permissionRequirements.contains(.fullDiskAccess),
                   !fullDiskAccessReport.isReady {
                    disabledToolIDs.insert(existing.id)
                    presentFullDiskAccessPrompt(reason: .manualCheck)
                }
            }

            var adoptedOldToolIDs = Set<String>()
            var adoptedGrantToolIDs = Set<String>()
            for adoption in scanAdoptions {
                let oldID = adoption.scannedTool.id
                let newID = adoption.preset.toolID
                guard let toolIndex = tools.firstIndex(where: { $0.id == oldID }),
                      tools[toolIndex] == adoption.scannedTool,
                      adoption.scannedTool.origin == .userDefined,
                      adoption.scannedTool.backend == .process,
                      adoption.scannedTool.provenance != nil,
                      !allTools.contains(where: { $0.id == newID }) else {
                    throw ToolValidationError.invalidArgument(
                        "Catalog tool \(adoption.preset.name) is no longer safe to adopt."
                    )
                }

                let wasDisabled = disabledToolIDs.contains(oldID)
                let adopted = try adoption.preset.draft.makeTool(id: newID)
                tools[toolIndex] = adopted

                disabledToolIDs.remove(oldID)
                if wasDisabled {
                    disabledToolIDs.insert(newID)
                } else {
                    disabledToolIDs.remove(newID)
                }
                invalidSavedToolIDs.remove(oldID)
                invalidSavedToolIDs.remove(newID)
                provenanceIdentityChangedToolIDs.remove(oldID)
                provenanceIdentityChangedToolIDs.remove(newID)
                provenanceContentUpdates.removeValue(forKey: oldID)
                provenanceContentUpdates.removeValue(forKey: newID)

                if !wasDisabled,
                   serverStatus.isRunning,
                   adopted.permissionRequirements.contains(.fullDiskAccess),
                   !fullDiskAccessReport.isReady {
                    disabledToolIDs.insert(newID)
                    presentFullDiskAccessPrompt(reason: .manualCheck)
                }

                adoptedOldToolIDs.insert(oldID)
                // Clear both identities. The stable ID may have a stale grant
                // from an older deleted installation, and adoption must never
                // inherit either authorization generation.
                adoptedGrantToolIDs.formUnion([oldID, newID])
            }

            var usedIDs = Set(allTools.map(\.id))
            for preset in addCandidates {
                guard usedIDs.insert(preset.toolID).inserted else {
                    throw ToolIdentifierError.duplicate(preset.toolID)
                }
                let added = try preset.draft.makeTool(id: preset.toolID)
                appendTool(added)
                // Broad escape hatches are installed for discoverability but
                // stay out of an agent's default shared surface.
                if added.isGenericCLIAdapter {
                    disabledToolIDs.insert(added.id)
                }
            }

            if !retiredIDs.isEmpty {
                tools.removeAll { retiredIDs.contains($0.id) }
                disabledToolIDs.subtract(retiredIDs)
                invalidSavedToolIDs.subtract(retiredIDs)
            }

            try persistUserDefinedTools()
            persistToolExposureState()
            for removedGrantToolID in retiredIDs.union(adoptedGrantToolIDs) {
                _ = clientToolPermissionStore.removeToolIDFromAllClients(removedGrantToolID)
            }
            clientToolPermissionSnapshot = clientToolPermissionStore.snapshot(matching: allTools)
            syncRunningToolSurface()
            appendLog(
                level: .info,
                "Updated \(sourceName): \(updateCandidates.count) refreshed, \(adoptedOldToolIDs.count) adopted, \(addCandidates.count) added, \(retiredIDs.count) retired."
            )
            return nil
        } catch {
            tools = originalTools
            disabledToolIDs = originalDisabledToolIDs
            clientToolPermissionSnapshot = originalAllowances
            invalidSavedToolIDs = originalInvalidToolIDs
            fullDiskAccessPrompt = originalFullDiskAccessPrompt
            provenanceIdentityChangedToolIDs = originalIdentityChangedToolIDs
            provenanceContentUpdates = originalProvenanceContentUpdates
            appendLog(level: .error, "Could not update \(sourceName): \(error.localizedDescription)")
            return error.localizedDescription
        }
    }

    /// A complete Federico provider scope owns its stable ID prefix. Updating
    /// one row never retires siblings; updating the full provider or publisher
    /// retires IDs no longer present in the current catalog.
    private static let federicoToolIDPrefixes = [
        "alexandria_", "habitctl_",
        "pocketctl_", "overctl_", "goodlinksctl_", "frames_",
        "iris_", "musicctl_"
    ]

    private func authoritativeFedericoToolIDPrefixes(
        for presets: [DefaultToolPreset]
    ) -> Set<String> {
        let requestedIDs = Set(presets.map(\.toolID))
        let allCatalogIDs = Set(DefaultToolPresetCatalog.presets.map(\.toolID))
        var authoritativePrefixes = Set<String>()
        for prefix in Self.federicoToolIDPrefixes {
            let completeProviderIDs = allCatalogIDs.filter { $0.hasPrefix(prefix) }
            guard !completeProviderIDs.isEmpty,
                  completeProviderIDs.isSubset(of: requestedIDs) else {
                continue
            }
            authoritativePrefixes.insert(prefix)
        }
        return authoritativePrefixes
    }

    private func adoptableScannedTools(
        in presets: [DefaultToolPreset],
        installationIndex: DefaultToolPresetInstallationIndex
    ) -> [DefaultToolPresetScanAdoption] {
        let authoritativePrefixes = authoritativeFedericoToolIDPrefixes(for: presets)
        guard !authoritativePrefixes.isEmpty else { return [] }
        return installationIndex.adoptableScannedTools(in: presets).filter { adoption in
            authoritativePrefixes.contains(where: adoption.preset.toolID.hasPrefix)
        }
    }

    private func retiredFedericoToolIDs(
        for presets: [DefaultToolPreset]
    ) -> Set<String> {
        let allCatalogIDs = Set(DefaultToolPresetCatalog.presets.map(\.toolID))
        let authoritativePrefixes = authoritativeFedericoToolIDPrefixes(for: presets)
        guard !authoritativePrefixes.isEmpty else { return [] }
        return Set(tools.compactMap { tool in
            guard tool.isUserDefined,
                  tool.mcpBridgeIdentity == nil,
                  authoritativePrefixes.contains(where: tool.id.hasPrefix),
                  !allCatalogIDs.contains(tool.id) else {
                return nil
            }
            return tool.id
        })
    }

    func addUserTools(from presets: [DefaultToolPreset], sourceName: String) -> String? {
        let candidates = installationIndex.installablePresets(in: presets)

        guard !candidates.isEmpty else {
            appendLog(level: .info, "All tools from \(sourceName) are already installed.")
            return nil
        }

        let originalTools = tools
        let originalDisabledToolIDs = disabledToolIDs

        do {
            var addedNotShared = 0
            var usedIDs = Set(allTools.map(\.id))
            for preset in candidates {
                guard !usedIDs.contains(preset.toolID) else {
                    throw ToolIdentifierError.duplicate(preset.toolID)
                }
                let tool = try preset.draft.makeTool(id: preset.toolID)
                appendTool(tool)
                usedIDs.insert(tool.id)
                // Every Flexible Command starts Not Shared, whoever made the
                // CLI: it runs whatever arguments an app sends, so sharing it
                // is the owner's explicit choice, not a side effect of "Add".
                if tool.isGenericCLIAdapter {
                    disabledToolIDs.insert(tool.id)
                }
                if !isToolExposed(tool) {
                    addedNotShared += 1
                }
            }

            try persistUserDefinedTools()
            persistToolExposureState()
            syncRunningToolSurface()

            let skipped = presets.count - candidates.count
            let disabledSuffix = addedNotShared > 0 ? " \(addedNotShared) added Not Shared." : ""
            let skippedSuffix = skipped > 0 ? " Skipped \(skipped) already installed." : ""
            appendLog(level: .info, "Added \(counted(candidates.count, "tool")) from \(sourceName).\(skippedSuffix)\(disabledSuffix)")
            return nil
        } catch {
            tools = originalTools
            disabledToolIDs = originalDisabledToolIDs
            appendLog(level: .error, "Could not add tools from \(sourceName): \(error.localizedDescription)")
            return error.localizedDescription
        }
    }

    func scanLocalMCPServers() {
        guard !localMCPScanState.isScanning else {
            appendLog(level: .warning, "Local MCP scan is already running.")
            return
        }

        localMCPScanState = .scanning
        localMCPErrorMessage = nil
        appendLog(level: .info, "Scanning this Mac for local MCP servers.")
        let scanner = localMCPScanner

        Task {
            let candidates = await scanner.scan(includeRemote: false, probe: true, includeRuntimeSources: true)
            // Full scans may deduplicate a configured row against the same
            // server reported by `claude mcp list`. Reconcile against a second
            // config-only view so runtime output can never hide real ownership.
            let configuredCandidates = await scanner.configuredCandidatesForReconciliation()
            let now = Date()
            reconcileImportedMCPTools(with: configuredCandidates)
            let marked = markMCPCandidatesWithNewFlags(candidates, clearAllNew: true)
            localMCPScanState = .loaded(marked, now)
            let bridgeableCount = candidates.filter(\.bridgeable).count
            appendLog(level: .info, "Found \(candidates.count) MCP server\(candidates.count == 1 ? "" : "s"); \(bridgeableCount) bridgeable.")
            let liveSnapshot = scanner.configSnapshot()
            persistMCPScanCacheAfterManualScan(
                candidates: candidates,
                configSnapshot: liveSnapshot,
                date: now
            )
        }
    }

    enum DiscoveryRefreshTrigger: Sendable {
        case launch
        case activation
        case manual
    }

    var localMCPFreshness: DiscoveryFreshness {
        guard let cache = mcpScanCache, cache.lastConfigScanDate != .distantPast else {
            return .neverScanned
        }
        let liveSnapshot = localMCPScanner.configSnapshot()
        if liveSnapshot != cache.configSnapshot {
            return .stale(lastScan: cache.lastConfigScanDate, reason: .configsChanged)
        }
        return .current(lastScan: cache.lastConfigScanDate)
    }

    var cliFreshness: DiscoveryFreshness {
        guard let cache = cliScanCache else {
            return .neverScanned
        }
        let liveFingerprints = cliScanner.fingerprints()
        for source in CLIScanSource.allCases {
            let live = liveFingerprints[source] ?? ""
            let cached = cache.fingerprint(for: source) ?? ""
            if live != cached {
                return .stale(lastScan: cache.lastScanDate, reason: .installRecordsChanged)
            }
        }
        return .current(lastScan: cache.lastScanDate)
    }

    var newUnimportedMCPCandidateCount: Int {
        let importedIdentities = Set(tools.compactMap { tool in
            tool.mcpBridgeServerIdentity ?? tool.mcpBridgeIdentity
        })
        return localMCPScanState.candidates.count { candidate in
            guard candidate.isNewSinceLastScan else { return false }
            if importedIdentities.contains(where: candidate.matchesPersistedServerIdentity) {
                return false
            }
            if let bridgeIdentity = candidate.bridgeIdentity,
               importedIdentities.contains(bridgeIdentity) {
                return false
            }
            return true
        }
    }

    func startAutomaticDiscovery() {
        // Called from the main window's task, which runs again for every new
        // window. One observer is enough.
        guard mcpActivationObserver == nil else { return }
        refreshLocalMCPDiscovery(trigger: .launch)
        mcpActivationObserver = NotificationCenter.default.addObserver(
            forName: NSApplication.didBecomeActiveNotification,
            object: nil,
            queue: .main
        ) { [weak self] _ in
            Task { @MainActor in
                guard let self else { return }
                let liveSnapshot = self.localMCPScanner.configSnapshot()
                if liveSnapshot != self.mcpScanCache?.configSnapshot {
                    self.refreshLocalMCPDiscovery(trigger: .activation)
                }
            }
        }
    }

    func refreshLocalMCPDiscovery(trigger: DiscoveryRefreshTrigger) {
        guard trigger != .manual else { return }
        guard !localMCPScanState.isScanning else { return }

        if trigger == .activation,
           let lastQuietMCPRefreshDate,
           Date().timeIntervalSince(lastQuietMCPRefreshDate) < 5 {
            return
        }

        let previousSnapshot = mcpScanCache?.configSnapshot
        let liveSnapshot = localMCPScanner.configSnapshot()
        if trigger == .activation, liveSnapshot == previousSnapshot {
            return
        }

        lastQuietMCPRefreshDate = Date()
        let scanner = localMCPScanner

        Task {
            let rawCandidates = await scanner.scan(
                includeRemote: false,
                probe: false,
                includeRuntimeSources: false
            )
            // Remote and duplicate-endpoint configs stay outside this local
            // import UI, but still count as present ownership.
            let configuredCandidates = await scanner.configuredCandidatesForReconciliation()
            reconcileImportedMCPTools(with: configuredCandidates)
            let candidates = markMCPCandidatesWithNewFlags(rawCandidates, clearAllNew: false)
            let now = Date()
            localMCPScanState = .loaded(candidates, now)
            persistMCPScanCacheQuiet(configSnapshot: liveSnapshot, date: now)

            let newCount = candidates.count(where: \.isNewSinceLastScan)
            if previousSnapshot != liveSnapshot || newCount > 0 {
                appendLog(
                    level: .info,
                    "Checked MCP configs: \(counted(candidates.count, "server")) detected, \(newCount) new."
                )
            }
        }
    }

    private func markMCPCandidatesWithNewFlags(
        _ candidates: [LocalMCPServerCandidate],
        clearAllNew: Bool
    ) -> [LocalMCPServerCandidate] {
        let seen = mcpScanCache?.hashedSeenBridgeIdentities ?? []
        return candidates.map { candidate in
            var copy = candidate
            if clearAllNew {
                copy.isNewSinceLastScan = false
            } else if let identity = candidate.canonicalRuntimeIdentity ?? candidate.bridgeIdentity {
                copy.isNewSinceLastScan = !seen.contains(Self.hashBridgeIdentity(identity))
            } else {
                copy.isNewSinceLastScan = false
            }
            return copy
        }
    }

    private func persistMCPScanCacheQuiet(configSnapshot: String, date: Date) {
        var cache = mcpScanCache ?? LocalMCPScanCache()
        cache.configSnapshot = configSnapshot
        cache.lastConfigScanDate = date
        persistMCPScanCache(cache)
    }

    private func persistMCPScanCacheAfterManualScan(
        candidates: [LocalMCPServerCandidate],
        configSnapshot: String,
        date: Date
    ) {
        var seen = mcpScanCache?.hashedSeenBridgeIdentities ?? []
        for candidate in candidates {
            if let identity = candidate.canonicalRuntimeIdentity ?? candidate.bridgeIdentity {
                seen.insert(Self.hashBridgeIdentity(identity))
            }
        }
        let cache = LocalMCPScanCache(
            hashedSeenBridgeIdentities: seen,
            configSnapshot: configSnapshot,
            lastConfigScanDate: date
        )
        persistMCPScanCache(cache)
    }

    private func persistMCPScanCache(_ cache: LocalMCPScanCache) {
        mcpScanCache = cache
        do {
            try FileManager.default.createDirectory(
                at: mcpScanCacheURL.deletingLastPathComponent(),
                withIntermediateDirectories: true
            )
            try JSONEncoder().encode(cache).write(to: mcpScanCacheURL, options: [.atomic])
        } catch {
            appendLog(level: .warning, "Could not save the MCP scan cache: \(error.localizedDescription)")
        }
    }

    private static func loadMCPScanCache(at url: URL) -> LocalMCPScanCache? {
        guard let data = try? Data(contentsOf: url),
              let cache = try? JSONDecoder().decode(LocalMCPScanCache.self, from: data) else {
            return nil
        }
        return cache
    }

    private static func hashBridgeIdentity(_ identity: String) -> String {
        SHA256.hash(data: Data(identity.utf8))
            .map { String(format: "%02x", $0) }
            .joined()
    }

    /// The scanner's synthesized candidate for an installed first-party CLI,
    /// if a scan has run since launch.
    func firstPartyMCPCandidate(for provider: FirstPartyMCPProvider) -> LocalMCPServerCandidate? {
        localMCPScanState.candidates.first {
            $0.source == FirstPartyMCPProviderCatalog.discoverySource && $0.name == provider.serverName
        }
    }

    /// Bridged tools already imported from a first-party CLI's MCP server.
    func importedFirstPartyMCPTools(for provider: FirstPartyMCPProvider) -> [ToolDefinition] {
        tools.filter { tool in
            guard let bridge = tool.mcpStdioBridge else { return false }
            return bridge.discoverySource == FirstPartyMCPProviderCatalog.discoverySource
                && bridge.serverName == provider.name
        }
    }

    /// Adds or refreshes one first-party CLI's bridged tools. Import goes
    /// through the same probe, id reservation, epoch preservation, and
    /// replacement path as any other discovered MCP server.
    func importFirstPartyMCPProvider(_ provider: FirstPartyMCPProvider) {
        if let candidate = firstPartyMCPCandidate(for: provider) {
            importLocalMCPServer(candidateID: candidate.id)
            return
        }
        guard localMCPWorkingServerID == nil, !localMCPScanState.isScanning else {
            appendLog(level: .warning, "Wait for the current MCP scan or import to finish.")
            return
        }
        let scanner = localMCPScanner
        Task {
            guard let candidate = scanner.firstPartyCandidate(for: provider) else {
                localMCPErrorMessage = "\(provider.name) is not installed on this Mac."
                startNextQueuedFirstPartyRefresh()
                return
            }
            localMCPScanState = localMCPScanState.insertingCandidate(candidate)
            importLocalMCPServer(candidateID: candidate.id)
        }
    }

    /// Re-imports every first-party provider that already has bridged tools,
    /// so a CLI upgrade that adds or renames tools flows into the catalog.
    /// Imports run one at a time, so the providers take turns: starting them
    /// all at once refreshed the first and refused the rest.
    func refreshImportedFirstPartyMCPProviders() -> Int {
        let providers = DefaultToolPresetCatalog.mcpProviders.filter {
            !importedFirstPartyMCPTools(for: $0).isEmpty
        }
        queuedFirstPartyRefreshes = providers
        startNextQueuedFirstPartyRefresh()
        return providers.count
    }

    private func startNextQueuedFirstPartyRefresh() {
        guard localMCPWorkingServerID == nil, !queuedFirstPartyRefreshes.isEmpty else { return }
        importFirstPartyMCPProvider(queuedFirstPartyRefreshes.removeFirst())
    }

    /// First-party servers waiting for their turn in "Update from Catalog".
    private var queuedFirstPartyRefreshes: [FirstPartyMCPProvider] = []

    func importLocalMCPServer(candidateID: String) {
        guard localMCPWorkingServerID == nil else {
            appendLog(level: .warning, "Wait for the current Local MCP import to finish.")
            return
        }
        guard var candidate = localMCPScanState.candidate(id: candidateID) else {
            localMCPErrorMessage = "Scan this Mac before importing that MCP server."
            return
        }
        guard candidate.bridgeable else {
            localMCPErrorMessage = candidate.reason ?? "This MCP server is scan-only."
            return
        }

        localMCPWorkingServerID = candidateID
        localMCPErrorMessage = nil
        let scanner = localMCPScanner

        Task {
            do {
                if candidate.probe?.tools.isEmpty ?? true {
                    candidate.probe = try await scanner.probe(candidate: candidate)
                }
                let refreshableTools = Self.refreshableImportedMCPTools(
                    for: candidate,
                    in: tools
                )
                let refreshableIDs = Set(refreshableTools.map(\.id))
                var preferredIDsByUpstreamToolName = [String: String]()
                for tool in refreshableTools {
                    guard let upstreamName = tool.mcpBridgeToolName else { continue }
                    if preferredIDsByUpstreamToolName[upstreamName] != nil {
                        throw ToolIdentifierError.duplicate(tool.id)
                    }
                    preferredIDsByUpstreamToolName[upstreamName] = tool.id
                }
                let reservedIDs = Set(allTools.map(\.id))
                    .union(DefaultToolPresetCatalog.presets.map(\.toolID))
                    .subtracting(refreshableIDs)
                let bridgeTools = try scanner.bridgeTools(
                    for: candidate,
                    existingIDs: reservedIDs,
                    preferredIDsByUpstreamToolName: preferredIDsByUpstreamToolName,
                    preferredServerName: refreshableTools.first?.mcpBridgeServerName
                )
                let replaced = try replaceLocalMCPBridgeTools(bridgeTools, bridgeIdentity: candidate.bridgeIdentity)
                localMCPScanState = localMCPScanState.replacingCandidate(candidate)
                localMCPWorkingServerID = nil
                appendLog(
                    level: .info,
                    "Imported \(counted(bridgeTools.count, "tool")) from \(candidate.displayName). Replaced \(replaced) existing bridge tool\(replaced == 1 ? "" : "s")."
                )
                startNextQueuedFirstPartyRefresh()
            } catch {
                localMCPWorkingServerID = nil
                defer { startNextQueuedFirstPartyRefresh() }
                if LocalMCPScanner.isSignInRequired(error) {
                    // Not a broken import: the server wants a sign-in first.
                    // The Tools page turns this into Sign-in Required + Sign In…
                    markMCPServerSignInRequired(candidateID: candidateID, message: error.localizedDescription)
                    appendLog(level: .warning, "\(candidate.displayName) needs a sign-in before its tools can be imported.")
                } else {
                    localMCPErrorMessage = error.localizedDescription
                    appendLog(level: .error, "Local MCP import failed: \(error.localizedDescription)")
                }
            }
        }
    }

    /// Records that a check answered "sign in first" so the server page shows
    /// the Sign In verb instead of a generic failure.
    private func markMCPServerSignInRequired(candidateID: String, message: String) {
        guard var candidate = localMCPScanState.candidate(id: candidateID) else { return }
        candidate.needsSignIn = true
        candidate.probeError = message
        localMCPScanState = localMCPScanState.replacingCandidate(candidate)
    }

    /// Pure ownership matcher shared by import refresh and regression tests.
    /// Canonical runtime identity handles exact duplicates; owner intersection
    /// keeps semantic IDs across endpoint/argv/env changes in the same config.
    /// Raw bridge identity is intentionally confined to one unambiguous legacy
    /// family because it omits header/environment semantics.
    nonisolated static func refreshableImportedMCPTools(
        for candidate: LocalMCPServerCandidate,
        in tools: [ToolDefinition]
    ) -> [ToolDefinition] {
        let candidateOwnerIDs = Set(candidate.configurationOwners.map(\.serverIdentity))
        let owned = tools.filter { tool in
            guard tool.isMCPBridge else { return false }
            let storedOwnerIDs = Set(tool.mcpBridgeDiscoveryOwners.map(\.serverIdentity))
            return candidate.matchesPersistedServerIdentity(tool.mcpBridgeServerIdentity) ||
                !candidateOwnerIDs.isDisjoint(with: storedOwnerIDs)
        }
        if !owned.isEmpty { return owned }

        let legacyNameMatches = tools.filter {
            $0.isMCPBridge &&
                $0.mcpBridgeServerIdentity == nil &&
                $0.mcpBridgeServerName?.caseInsensitiveCompare(candidate.displayName) == .orderedSame
        }
        let legacyFamilies = Set(legacyNameMatches.compactMap(\.mcpBridgeIdentity))
        guard legacyFamilies.count == 1,
              legacyFamilies.first == candidate.bridgeIdentity else {
            return []
        }
        return legacyNameMatches
    }

    /// True only while THIS candidate imports. Comparing optionals directly
    /// (`localMCPWorkingServerID == server.candidate?.id`) read `nil == nil`
    /// as importing, so servers whose original config disappeared spun on
    /// "Importing tools…" forever.
    func isImportingLocalMCPServer(candidateID: String?) -> Bool {
        guard let candidateID else { return false }
        return localMCPWorkingServerID == candidateID
    }

    /// A quiet check of one HTTP server the moment its Tools page opens, so
    /// the page shows a live state (signed in, sign-in required, failed)
    /// without a manual Refresh. HTTP only: no process is launched, and
    /// nothing is imported or shared. Stdio servers keep the explicit Refresh.
    func checkMCPServer(candidateID: String) {
        guard localMCPCheckingServerID == nil,
              localMCPWorkingServerID != candidateID,
              mcpSignInServerID != candidateID,
              let candidate = localMCPScanState.candidate(id: candidateID),
              candidate.transport == .http,
              candidate.bridgeable else {
            return
        }
        localMCPCheckingServerID = candidateID
        let scanner = localMCPScanner
        Task {
            var checked = candidate
            do {
                checked.probe = try await scanner.probe(candidate: candidate, timeoutCapSeconds: 10)
                checked.probeError = nil
                checked.needsSignIn = false
            } catch {
                checked.probeError = error.localizedDescription
                checked.needsSignIn = LocalMCPScanner.isSignInRequired(error)
            }
            if localMCPCheckingServerID == candidateID {
                localMCPScanState = localMCPScanState.replacingCandidate(checked)
                localMCPCheckingServerID = nil
            }
        }
    }

    // MARK: Upstream sign-in (D62)

    /// True when MacRemote holds its own sign-in for this HTTP MCP server.
    func isMCPServerSignedIn(serverURL: String?) -> Bool {
        guard let serverURL else { return false }
        return upstreamOAuthStore.isSignedIn(serverURL)
    }

    /// Signs in to a server that answered a check with "sign in first": the
    /// browser opens its approval page, the reply lands on this Mac, and the
    /// candidate is re-checked with MacRemote's own token. A family that was
    /// already imported refreshes right away so its tools carry the new
    /// sign-in instead of a dead header.
    func signInToMCPServer(candidateID: String) {
        guard mcpSignInServerID == nil else {
            appendLog(level: .warning, "Wait for the current sign-in to finish.")
            return
        }
        guard let candidate = localMCPScanState.candidate(id: candidateID),
              candidate.transport == .http,
              let url = candidate.url else {
            mcpSignInErrorMessage = "Scan this Mac before signing in to that MCP server."
            return
        }

        mcpSignInServerID = candidateID
        mcpSignInErrorMessage = nil
        appendLog(level: .info, "Signing in to \(candidate.displayName): approve the request in your browser.")
        let client = upstreamOAuth
        let scanner = localMCPScanner

        Task {
            do {
                _ = try await client.signIn(serverURL: url, serverName: candidate.displayName)
                var signedIn = candidate.signedInWithMacRemote()
                do {
                    signedIn.probe = try await scanner.probe(candidate: signedIn)
                } catch {
                    signedIn.probeError = error.localizedDescription
                    signedIn.needsSignIn = LocalMCPScanner.isSignInRequired(error)
                }
                localMCPScanState = localMCPScanState.replacingCandidate(signedIn)
                mcpSignInServerID = nil
                appendLog(level: .info, "Signed in to \(candidate.displayName).")
                if signedIn.probe != nil, hasImportedTools(for: signedIn) {
                    importLocalMCPServer(candidateID: candidateID)
                }
            } catch {
                mcpSignInServerID = nil
                mcpSignInErrorMessage = error.localizedDescription
                appendLog(level: .error, "Sign-in to \(candidate.displayName) failed: \(error.localizedDescription)")
            }
        }
    }

    /// Revokes MacRemote's sign-in for this server (when it offers revocation)
    /// and forgets the token. Imported tools stay; they ask for a sign-in.
    func signOutOfMCPServer(candidateID: String) {
        guard let candidate = localMCPScanState.candidate(id: candidateID),
              let url = candidate.url else {
            return
        }
        let client = upstreamOAuth
        Task {
            await client.signOut(serverURL: url)
            var copy = candidate
            copy.needsSignIn = copy.usesUpstreamOAuth
            localMCPScanState = localMCPScanState.replacingCandidate(copy)
            appendLog(level: .info, "Signed out of \(candidate.displayName). Its imported tools ask for a sign-in until you sign in again.")
        }
    }

    private func hasImportedTools(for candidate: LocalMCPServerCandidate) -> Bool {
        tools.contains { tool in
            guard tool.isMCPBridge else { return false }
            if candidate.matchesPersistedServerIdentity(tool.mcpBridgeServerIdentity) {
                return true
            }
            return tool.mcpBridgeIdentity == candidate.bridgeIdentity
        }
    }

    func setLocalMCPBridgeServerEnabled(bridgeIdentity: String, enabled: Bool) -> String? {
        let serverTools = tools.filter {
            ($0.mcpBridgeServerIdentity ?? $0.mcpBridgeIdentity) == bridgeIdentity
        }
        guard !serverTools.isEmpty else {
            return "No imported tools found for that MCP server."
        }

        let failures: [String]
        if enabled {
            failures = enableToolsAfterValidation(serverTools)
        } else {
            failures = []
            for tool in serverTools {
                disabledToolIDs.insert(tool.id)
            }
        }

        persistToolExposureState()
        syncRunningToolSurface()
        let serverName = serverTools.first?.mcpBridgeServerName ?? "Local MCP"
        if enabled, !failures.isEmpty {
            let sharedCount = serverTools.count { isToolExposed($0) }
            appendLog(
                level: .warning,
                "Shared \(counted(sharedCount, "imported tool")) for \(serverName); \(failures.count) stayed Not Shared."
            )
        } else {
            appendLog(
                level: enabled ? .info : .warning,
                "\(enabled ? "Shared" : "Stopped sharing") \(counted(serverTools.count, "imported tool")) for \(serverName)."
            )
        }
        return failures.first
    }

    /// Imported tools belong to the configured server that the scanner found,
    /// not to MacRemote itself. Once a readable config no longer contains that
    /// server, remove every owned tool, sharing choice, and Always Allow rule.
    /// A server that is offline or has an unavailable executable still yields a
    /// candidate and is preserved. Runtime-only Claude discovery is deliberately
    /// excluded because a failed `claude mcp list` is not proof of removal.
    @discardableResult
    func reconcileImportedMCPTools(with candidates: [LocalMCPServerCandidate]) -> Int {
        let configuredCandidates = candidates.filter { $0.source != "claude_runtime" }
        let presentServerIdentities = Set(configuredCandidates.flatMap { candidate in
            [candidate.persistedServerIdentity] + candidate.configurationOwners.map(\.serverIdentity)
        })
        let unreadableSourceScopes = configuredCandidates.compactMap {
            candidate -> (source: String, path: String)? in
            guard let scopePath = candidate.sourceReadFailureScopePath else { return nil }
            return (candidate.source, scopePath)
        }

        let orphanedTools = tools.filter { tool in
            guard tool.isMCPBridge else { return false }
            guard let serverIdentity = tool.mcpBridgeServerIdentity else {
                // Absence is not proof for legacy or manually-authored rows.
                return false
            }
            let owners = tool.mcpBridgeDiscoveryOwners
            if owners.isEmpty {
                guard let source = tool.mcpBridgeDiscoverySource,
                      let sourcePath = tool.mcpBridgeDiscoverySourcePath,
                      !sourcePath.isEmpty else {
                    return false
                }
                if source == "claude_runtime" || source == "manual" {
                    return false
                }
            }
            if owners.contains(where: { $0.source == "claude_runtime" || $0.source == "manual" }) {
                return false
            }
            if owners.contains(where: { owner in
                let standardizedSourcePath = URL(fileURLWithPath: owner.sourcePath).standardizedFileURL.path
                return unreadableSourceScopes.contains(where: { scope in
                    guard scope.source == owner.source else { return false }
                    let standardizedScope = URL(fileURLWithPath: scope.path).standardizedFileURL.path
                    return standardizedSourcePath == standardizedScope ||
                        standardizedSourcePath.hasPrefix(standardizedScope + "/")
                })
            }) {
                return false
            }
            let toolClaims = Set([serverIdentity] + owners.map(\.serverIdentity))
            return toolClaims.isDisjoint(with: presentServerIdentities)
        }
        guard !orphanedTools.isEmpty else { return 0 }

        let removedIDs = Set(orphanedTools.map(\.id))
        let removedSeenHashes = Set(orphanedTools.flatMap { tool in
            [tool.mcpBridgeServerIdentity, tool.mcpBridgeIdentity]
                .compactMap { $0 }
                .map(Self.hashBridgeIdentity)
        })
        let removedServerCount = Set(orphanedTools.map {
            $0.mcpBridgeServerIdentity ?? $0.mcpBridgeIdentity ?? $0.id
        }).count
        let originalTools = tools
        let originalDisabledToolIDs = disabledToolIDs
        let originalIdentityChangedToolIDs = provenanceIdentityChangedToolIDs
        let originalContentUpdates = provenanceContentUpdates
        let originalInvalidToolIDs = invalidSavedToolIDs

        tools.removeAll { removedIDs.contains($0.id) }
        disabledToolIDs.subtract(removedIDs)
        provenanceIdentityChangedToolIDs.subtract(removedIDs)
        for id in removedIDs {
            provenanceContentUpdates[id] = nil
            invalidSavedToolIDs.remove(id)
        }

        do {
            try persistUserDefinedTools()
            persistToolExposureState()
            if var cache = mcpScanCache, !removedSeenHashes.isEmpty {
                cache.hashedSeenBridgeIdentities.subtract(removedSeenHashes)
                persistMCPScanCache(cache)
            }
            for id in removedIDs {
                _ = clientToolPermissionStore.removeToolIDFromAllClients(id)
            }
            clientToolPermissionSnapshot = clientToolPermissionStore.snapshot(matching: allTools)
            syncRunningToolSurface()
            appendLog(
                level: .warning,
                "Removed \(orphanedTools.count) imported MCP tool\(orphanedTools.count == 1 ? "" : "s") from \(removedServerCount) server\(removedServerCount == 1 ? "" : "s") whose original config is gone."
            )
            return orphanedTools.count
        } catch {
            tools = originalTools
            disabledToolIDs = originalDisabledToolIDs
            provenanceIdentityChangedToolIDs = originalIdentityChangedToolIDs
            provenanceContentUpdates = originalContentUpdates
            invalidSavedToolIDs = originalInvalidToolIDs

            // A corrupt/locked registry must not leave a proven orphan callable
            // merely because its removal could not be persisted safely.
            disabledToolIDs.formUnion(removedIDs)
            persistToolExposureState()
            syncRunningToolSurface()
            appendLog(
                level: .error,
                "Could not remove imported MCP tools whose config is gone; sharing was turned off: \(error.localizedDescription)"
            )
            return 0
        }
    }

