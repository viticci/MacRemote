        guard let client = connectedClients.first(where: { $0.id == clientID }) else {
            return .failure(.appNotFound)
        }
        guard let revocation = ConnectedAppSignOutResult.revoke(
            client: client,
            authCoordinator: authCoordinator,
            toolCallApprovalCoordinator: toolCallApprovalCoordinator,
            permissionStore: clientToolPermissionStore
        ) else {
            return .failure(.appNotFound)
