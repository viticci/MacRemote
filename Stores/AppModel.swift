    private func refreshFullDiskAccessStatus() async -> FullDiskAccessReport {
        if let inFlight = fullDiskAccessRefreshTask {
            return await inFlight.value
        }

        let refresh = Task { () -> FullDiskAccessReport in
            fullDiskAccessReport = FullDiskAccessReport(
                state: .checking,
                detail: "Checking protected-data access from MacRemote.",
                targets: fullDiskAccessReport.targets
            )
            var report = await fullDiskAccessService.check(
                environment: AppModel.toolEnvironment,
                tools: exposedTools
            )

            if report.requiresManualConfirmation,
               let signature = report.confirmationSignature,
               userDefaults.string(forKey: Self.confirmedFullDiskAccessSignatureKey) == signature {
                report = FullDiskAccessReport(
                    state: .ready,
                    detail: "Manual Full Disk Access confirmation is recorded for the current shared tools that require Full Disk Access.",
                    targets: report.targets,
                    confirmationSignature: signature,
                    automaticChecksPassed: report.automaticChecksPassed
                )
            }

            fullDiskAccessReport = report
            return report
        }
        fullDiskAccessRefreshTask = refresh
        let report = await refresh.value
        fullDiskAccessRefreshTask = nil
        return report
    }

    private func refreshMacOSPrivacyAccessStatus() async -> MacOSPrivacyAccessReport {
        macOSPrivacyAccessReport = MacOSPrivacyAccessReport(
            state: .checking,
            detail: "Checking macOS privacy access from MacRemote.",
            checkedRequirements: macOSPrivacyAccessReport.checkedRequirements
        )
        let report = await macOSPrivacyAccessService.check(tools: exposedTools)
        macOSPrivacyAccessReport = report
        return report
    }

    private func refreshAccessStatusForServerStart() async -> Bool {
        if exposedToolsRequireFullDiskAccess {
            let report = await refreshFullDiskAccessStatus()
            guard report.isReady else {
                presentFullDiskAccessPrompt(reason: .serverStart)
                appendLog(level: .warning, "Blocked server start: grant Full Disk Access before sharing tools that need it.")
                return false
            }
        }

        if exposedToolsRequireCheckedMacOSPrivacyAccess {
            let report = await refreshMacOSPrivacyAccessStatus()
            guard report.isReady else {
                revealReadinessRow(.privacyPermissions)
                appendLog(level: .warning, "Blocked server start: \(singleLine(report.detail))")
                return false
            }
        }

        return true
    }

    nonisolated static func cloudflareFailurePresentation(
        for error: Error,
        stage: CloudflareDeployStage?,
        apiToken: String
    ) -> (message: String, technicalDetail: String?) {
        if let serviceError = error as? CloudflareServiceError {
            switch serviceError {
            case .api(let detail):
                return (
                    cloudflareFailureMessage(for: stage),
                    sanitizedCloudflareTechnicalDetail(detail, apiToken: apiToken)
                )
            default:
                return (serviceError.localizedDescription, nil)
            }
        }

        return (
            cloudflareFailureMessage(for: stage),
            sanitizedCloudflareTechnicalDetail(error.localizedDescription, apiToken: apiToken)
        )
    }

    private nonisolated static func cloudflareFailureMessage(for stage: CloudflareDeployStage?) -> String {
        switch stage {
        case nil:
            "MacRemote couldn't load your Cloudflare domains. Check the API token or Wrangler sign-in, then try again."
        case .checkAccess:
            "MacRemote couldn't check the API token and existing Cloudflare resources. Check the API token, then try again."
        case .createTunnel:
            "MacRemote couldn't create or update the Cloudflare tunnel. Try again."
        case .configureDNS:
            "MacRemote couldn't configure DNS for this hostname. Check the selected domain, then try again."
        case .start:
            "MacRemote couldn't start the public link. Check Cloudflare's helper, then try again."
        }
    }

    nonisolated static func sanitizedCloudflareTechnicalDetail(_ value: String, apiToken: String) -> String? {
        var sanitized = value
        if !apiToken.isEmpty {
            sanitized = sanitized.replacingOccurrences(of: apiToken, with: "[redacted]")
        }
        if let regex = try? NSRegularExpression(
            pattern: #"(?i)(authorization|api[-_ ]?token|bearer)\s*[:=]?\s*[A-Za-z0-9._~+/=-]+"#
        ) {
            let range = NSRange(sanitized.startIndex..<sanitized.endIndex, in: sanitized)
            sanitized = regex.stringByReplacingMatches(
                in: sanitized,
                range: range,
                withTemplate: "$1 [redacted]"
            )
        }
        sanitized = sanitized
            .split(whereSeparator: \.isNewline)
            .joined(separator: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard !sanitized.isEmpty else { return nil }
        return String(sanitized.prefix(1_024))
    }

    private func singleLine(_ value: String) -> String {
        value
            .split(whereSeparator: \.isNewline)
            .joined(separator: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    private func handleServerEvent(_ event: LocalMCPServerEvent) {
        switch event {
        case .log(let level, let message):
            appendLog(level: level, message)
        case .approvalsChanged(let approvals):
            handleAuthorizationApprovalsChanged(approvals)
        case .clientsChanged(let clients):
            setConnectedClients(clients)
        case .clientSuppliedIconsChanged(let clientID, let icons):
            clientSuppliedIcons[clientID] = icons
        }
    }

    /// Not private so tests can deliver an event without a running helper.
    func handleTunnelEvent(_ event: TunnelServiceEvent) {
        switch event {
        case .log(let message):
            appendLog(level: .info, message)
        case .connectionLost:
            // The helper is still running and reconnects by itself, so the
            // session and its watchdog stay. Only the claim that the link is
            // up is withdrawn until `started` arrives again. "Reconnecting"
            // is the glossary's word for a dropped public link.
            guard tunnelStatus.isRunning else { return }
            tunnelStatus = .reconnecting(attempt: 1)
            appendLog(level: .warning, "Your public link lost its connection to Cloudflare. It reconnects by itself when the connection returns.")
        case .started(let publicURL):
            tunnelStatus = .running(publicURL)
            recordTunnelSupervision(publicURL: publicURL)
            tunnelWatchdog.notifyTunnelStarted()
            appendLog(level: .info, "Cloudflare Tunnel ready at \(publicURL.absoluteString).")
            if let hostname = launchGoPublicHostname {
                // D76: every automatic go-public is announced, once.
                launchGoPublicHostname = nil
                appendLog(level: .warning, "\(hostname) went public at launch, as set in Settings › General.")
                postStatusNotification(
                    title: "Your public link is live",
                    body: "\(hostname) went public when MacRemote opened. New apps still need your approval to connect."
                )
            }
            if case .named(let deployment, let fromSavedToken) = activeTunnelMode {
                let alreadyDeployed = cloudflareCustomDomainState == .deployed(deployment.hostname)
                cloudflareCustomDomainState = .deployed(deployment.hostname)
                if !alreadyDeployed, !fromSavedToken {
                    appendLog(
                        level: .info,
                        "Deployed Cloudflare custom domain tunnel for \(deployment.hostname) with \(connectorAuthMode.protectionTitle) sign-in."
                    )
                }
            }
        case .stopped:
            if tunnelWatchdog.shouldIgnoreStoppedEvent() {
                return
            }
            deactivateTunnelWatchdog()
            clearTunnelSupervision()
            tunnelStatus = tunnelService.status(localServerURL: localServerURL)
            appendLog(level: .info, "Cloudflare Tunnel process exited.")
        case .failed(let message):
            appendLog(level: .error, message)
            if tunnelWatchdog.handleUnexpectedFailure(message) {
                return
            }
            if case .named = activeTunnelMode {
                cloudflareCustomDomainState = .failed(.deploying(stage: .start, message: message))
            }
            clearTunnelSupervision()
            tunnelStatus = .failed(message)
        case .runTokenRefused(let message):
            guard case .named(let deployment, fromSavedToken: true) = activeTunnelMode else {
                // A tunnel deployed a moment ago can be rejected for a few
                // seconds while Cloudflare learns about it. The usual
                // retries cover that.
                handleTunnelEvent(.failed(message))
                return
            }
            // The saved key no longer works, so retrying it cannot help.
            // Delete it and say what to do; the next Go Public opens the
            // Address card, where a deploy saves a new one.
            appendLog(level: .error, message)
            deactivateTunnelWatchdog()
            clearTunnelSupervision()
            cloudflareRunTokenStore.delete()
            let refusal = "Cloudflare no longer accepts the saved key for \(deployment.hostname). Deploy your domain again from Address."
            cloudflareCustomDomainState = .failed(.deploying(stage: .start, message: refusal))
            tunnelStatus = .failed(refusal)
            appendLog(level: .error, refusal)
        }
    }

    private func deactivateTunnelWatchdog() {
        tunnelWatchdog.deactivate()
        activeTunnelMode = .none
        launchGoPublicHostname = nil
        // The session is over, so the next start may pick a newly installed
        // helper. While the session lives, every watchdog restart reuses the
        // executable the session began with.
        tunnelService.clearSessionPin()
    }

    private func performTunnelRestartForWatchdog() throws {
        guard let localServerURL else {
            throw TunnelServiceError.cloudflaredUnavailable
        }

        switch activeTunnelMode {
        case .quick:
            try tunnelService.startQuickTunnel(localServerURL: localServerURL) { [weak self] event in
                Task { @MainActor in
                    self?.handleTunnelEvent(event)
                }
            }
        case .named(let deployment, _):
            try tunnelService.startNamedTunnel(deployment: deployment) { [weak self] event in
                Task { @MainActor in
                    self?.handleTunnelEvent(event)
                }
            }
        case .none:
            throw TunnelServiceError.cloudflaredUnavailable
        }
    }

    private func handleTunnelWatchdogRecoveryFailed(_ message: String) {
        let namedTunnelWasActive: Bool
        if case .named = activeTunnelMode {
            namedTunnelWasActive = true
        } else {
            namedTunnelWasActive = false
        }
        deactivateTunnelWatchdog()
        clearTunnelSupervision()
        tunnelStatus = .failed(message)
        if namedTunnelWasActive {
            cloudflareCustomDomainState = .failed(.deploying(stage: .start, message: message))
        }
        appendLog(level: .error, message)
        // The owner is usually away from the Mac when this happens, and apps
        // that rely on the link have just lost it.
        postStatusNotification(
            title: "Your public link stopped",
            body: "MacRemote could not bring it back. Open MacRemote to go public again."
        )
    }

    private static func makeTunnelWatchdog(
        for model: AppModel,
        tunnelService: TunnelService,
        cloudflaredManager: CloudflaredManager,
        originHealthChecker: URLOriginHealthChecker
    ) -> TunnelWatchdog {
        TunnelWatchdog(environment: TunnelWatchdog.Environment(
            sleep: { duration in
                try await Task.sleep(for: duration)
            },
            isTunnelProcessRunning: {
                tunnelService.isProcessRunning()
            },
            refreshTunnelConnection: {
                await tunnelService.refreshEdgeConnection()
            },
            stopTunnelIfNeeded: { [weak model] in
                await MainActor.run {
                    model?.tunnelService.stop()
                }
            },
            restartTunnel: { [weak model] in
                // A relaunch reuses the executable this session started with, so
                // that exact file is proven again first — off the main actor,
                // and cheap once the verification cache is warm. A copy that no
                // longer verifies is quarantined by the check itself, and the
                // restart fails rather than falling back to a different binary.
                if let pinned = tunnelService.sessionExecutablePin() {
                    let verified = await Task.detached(priority: .utility) {
                        cloudflaredManager.verifyLaunchPath(pinned)
                    }.value
                    guard verified else {
                        throw TunnelServiceError.helperNoLongerVerified
                    }
                }
                try await MainActor.run {
                    guard let model else { throw TunnelServiceError.cloudflaredUnavailable }
                    try model.performTunnelRestartForWatchdog()
                }
            },
            checkOriginHealth: { localServerURL in
                await originHealthChecker.isOriginHealthy(at: localServerURL)
            },
            onReconnecting: { [weak model] attempt in
                Task { @MainActor in
                    model?.tunnelStatus = .reconnecting(attempt: attempt)
                }
            },
            onRecoveryFailed: { [weak model] message in
                Task { @MainActor in
                    model?.handleTunnelWatchdogRecoveryFailed(message)
                }
            },
            onLog: { [weak model] message in
                Task { @MainActor in
                    model?.appendLog(level: .warning, message)
                }
            }
        ))
    }
}

