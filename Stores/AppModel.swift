            return
        }
        guard tunnelStatus.isRunning == false else {
            appendLog(level: .warning, "Stop the current tunnel before deploying a custom domain tunnel.")
            return
        }
        guard tunnelStatus != .unavailable else {
            let message = CloudflareServiceError.cloudflaredUnavailable.localizedDescription
            cloudflareCustomDomainState = .failed(.deploying(stage: .start, message: message))
            appendLog(level: .warning, message)
            return
        }
        guard let selectedCloudflareZone else {
            cloudflareCustomDomainState = .failed(.deploying(
                stage: .checkAccess,
                message: CloudflareServiceError.zoneRequired.localizedDescription
            ))
            appendLog(level: .warning, "Select a Cloudflare domain before deploying.")
            return
        }
        let subdomain = cloudflareDraft.subdomain
        guard customCloudflareHostnamePreview != nil else {
            let message = CloudflareServiceError.invalidSubdomain.localizedDescription
            cloudflareCustomDomainState = .failed(.deploying(stage: .checkAccess, message: message))
            appendLog(level: .warning, message)
            return
        }
        let apiToken = cloudflareDraft.trimmedAPIToken
        guard CloudflareService.canLoadZones(apiToken: apiToken, wranglerPath: cloudflareService.wranglerPath()) else {
            let message = CloudflareServiceError.wranglerUnavailable.localizedDescription
            cloudflareCustomDomainState = .failed(.deploying(stage: .checkAccess, message: message))
            appendLog(level: .warning, message)
            return
        }
        let expectedTunnelID = savedCloudflareDomain.flatMap {
            $0.matches(zone: selectedCloudflareZone, subdomain: subdomain) ? $0.tunnelID : nil
        }

        cloudflareCustomDomainState = localServerURL == nil ? .preparingLocalServer : .deploying(.checkAccess)

        Task { [self] in
            do {
                guard let localServerURL = await ensureLocalServerRunning() else {
                    let message: String
                    if case .failed(let detail) = serverStatus {
                        message = detail
                    } else {
                        message = customDomainDeployHint
                    }
                    tunnelStatus = tunnelService.status(localServerURL: self.localServerURL)
                    cloudflareCustomDomainState = .failed(.preparingLocalServer(message))
                    appendLog(level: .warning, message)
                    return
                }

                cloudflareCustomDomainState = .deploying(.checkAccess)
                tunnelStatus = .starting
                appendLog(level: .info, "Deploying Cloudflare custom domain tunnel for \(customCloudflareHostnamePreview ?? selectedCloudflareZone.name).")

                let deployment = try await cloudflareService.deployCustomDomain(
                    zone: selectedCloudflareZone,
                    subdomain: subdomain,
                    localServerURL: localServerURL,
                    apiToken: apiToken,
                    expectedTunnelID: expectedTunnelID,
                    progress: { [weak self] stage in
                        await MainActor.run {
                            self?.cloudflareCustomDomainState = .deploying(stage)
                        }
                    }
                )
                lastCloudflareDeployment = deployment
                rememberCloudflareDomain(deployment)
                activeTunnelMode = .named(deployment, fromSavedToken: false)
                tunnelWatchdog.activate(localServerURL: localServerURL)
                try tunnelService.startNamedTunnel(deployment: deployment) { [weak self] event in
                    Task { @MainActor in
                        self?.handleTunnelEvent(event)
                    }
                }
            } catch {
                let failedStage = cloudflareCustomDomainState.activeDeployStage ?? .checkAccess
                let failure = Self.cloudflareFailurePresentation(
                    for: error,
                    stage: failedStage,
                    apiToken: apiToken
                )
                deactivateTunnelWatchdog()
                tunnelStatus = tunnelService.status(localServerURL: localServerURL)
                cloudflareCustomDomainState = .failed(.deploying(
                    stage: failedStage,
                    message: failure.message,
                    technicalDetail: failure.technicalDetail
                ))
                appendLog(level: .error, "Cloudflare custom domain deploy failed: \(failure.technicalDetail ?? failure.message)")
            }
        }
    }

