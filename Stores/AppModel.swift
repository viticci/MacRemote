    private func appendTool(_ tool: ToolDefinition) {
        tools.append(tool)
        let canExposeImmediately = !serverStatus.isRunning ||
            !tool.permissionRequirements.contains(.fullDiskAccess) ||
            fullDiskAccessReport.isReady
