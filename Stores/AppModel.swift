    }

    var hasLockedOAuthCredentials: Bool {
        !lockedOAuthClientIDs.isEmpty
    }

    private func refreshOAuthClientCredentials() {
        let loaded = oauthClientCredentialStore.loadAllDetailed(interactive: true)
        oauthClientCredentials = loaded.credentials
        lockedOAuthClientIDs = loaded.lockedClientIDs
    }

    /// User-initiated from Settings › Security: performs an interactive Keychain
    /// read, so the macOS password prompt appears at a moment the user chose.
    func unlockOAuthCredentials() {
        let previouslyLocked = lockedOAuthClientIDs.count
        refreshOAuthClientCredentials()
        authCoordinator.updateClientAuthentication(currentOAuthClientAuthenticationPolicy)
        if lockedOAuthClientIDs.isEmpty, previouslyLocked > 0 {
            appendLog(level: .info, "Unlocked \(previouslyLocked) saved sign-in credential\(previouslyLocked == 1 ? "" : "s") from the Keychain.")
        } else if hasLockedOAuthCredentials {
            appendLog(level: .warning, "Sign-in credentials are still locked — the Keychain request was not approved.")
        }
    }

    func generateOAuthClientCredentials(label: String? = nil) {
        do {
            let credential = try oauthClientCredentialStore.generate(
                label: label ?? defaultOAuthClientCredentialLabel
            )
            refreshOAuthClientCredentials()
            authCoordinator.updateClientAuthentication(currentOAuthClientAuthenticationPolicy)
            appendLog(level: .info, "Generated OAuth client credentials for \(credential.label).")
        } catch {
            appendLog(level: .error, "Could not generate OAuth client credentials: \(error.localizedDescription)")
        }
    }

    func rotateOAuthClientCredentials(clientID: String) {
        do {
            guard let replacement = try oauthClientCredentialStore.rotate(clientID: clientID) else {
                appendLog(level: .warning, "OAuth client credentials not found.")
                return
            }
            revokeOAuthStateForCredential(clientID: clientID, action: "Rotated OAuth client credentials for \(replacement.label).")
            refreshOAuthClientCredentials()
            authCoordinator.updateClientAuthentication(currentOAuthClientAuthenticationPolicy)
        } catch {
            appendLog(level: .error, "Could not rotate OAuth client credentials: \(error.localizedDescription)")
        }
    }

    func deleteOAuthClientCredentials(clientID: String) {
        do {
            let label = oauthClientCredentials.first { $0.clientID == clientID }?.label ?? "OAuth Client"
            try oauthClientCredentialStore.delete(clientID: clientID)
            revokeOAuthStateForCredential(clientID: clientID, action: "Deleted OAuth client credentials for \(label).")
            refreshOAuthClientCredentials()
            authCoordinator.updateClientAuthentication(currentOAuthClientAuthenticationPolicy)
        } catch {
            appendLog(level: .error, "Could not delete OAuth client credentials: \(error.localizedDescription)")
        }
    }

    private func revokeOAuthStateForCredential(clientID: String, action: String) {
        let connectedClient = connectedClients.first { $0.id == clientID }
        let summary = authCoordinator.revokeClient(id: clientID)
        approvals = authCoordinator.approvalSnapshot()
        notifiedAuthorizationRequestIDs.formIntersection(Set(approvals.map(\.id)))
        setConnectedClients(authCoordinator.connectedClientSnapshot())
        if let connectedClient {
            clientToolPermissionSnapshot = clientToolPermissionStore.removeClient(
                clientID,
                clientTrustID: connectedClient.trustID
            )
        }
        appendLog(
            level: .warning,
            "\(action) Revoked \(summary?.accessTokens ?? 0) access tokens and \(summary?.refreshTokens ?? 0) refresh tokens."
        )
    }

    func deleteOAuthClient(id clientID: String) -> String? {
        guard let client = connectedClients.first(where: { $0.id == clientID }) else {
            return "Client not found."
        }
        guard let summary = authCoordinator.revokeClient(id: clientID) else {
            return "Client not found."
        }

        approvals = authCoordinator.approvalSnapshot()
        notifiedAuthorizationRequestIDs.formIntersection(Set(approvals.map(\.id)))
        setConnectedClients(authCoordinator.connectedClientSnapshot())
        clientToolPermissionSnapshot = clientToolPermissionStore.removeClient(
            clientID,
            clientTrustID: client.trustID
        )
        appendLog(
            level: .warning,
            "Deleted OAuth client \(client.name): \(summary.authorizations) authorizations, \(summary.accessTokens) access tokens, \(summary.refreshTokens) refresh tokens."
        )
        return nil
    }

    func setConnectorProvider(_ provider: ConnectorProviderProfile) {
        guard connectorProvider != provider else { return }
        connectorProvider = provider
        setConnectorAuthMode(provider.recommendedAuthMode)
    }

    func setConnectorAuthMode(_ mode: ConnectorAuthMode) {
        if mode.requiresOAuthClientSecret, oauthClientCredentials.isEmpty {
            generateOAuthClientCredentials()
        }
        if mode == .singleHeaderToken, connectorHeaderToken == nil {
            generateConnectorHeaderToken()
        }
        connectorAuthMode = mode
        persistConnectorSettings()
        authCoordinator.updateClientAuthentication(currentOAuthClientAuthenticationPolicy)
        syncConnectorHeaderToken()
    }

    private func generateConnectorHeaderToken() {
        do {
            connectorHeaderToken = try connectorHeaderTokenStore.generate(label: "Connector Header Token")
            appendLog(level: .info, "Generated the Single Header sign-in token.")
        } catch {
            appendLog(level: .error, "Could not generate the Single Header token: \(error.localizedDescription)")
        }
    }

    func rotateConnectorHeaderToken() {
        connectorHeaderTokenStore.clear()
        connectorHeaderToken = nil
        generateConnectorHeaderToken()
        syncConnectorHeaderToken()
        appendLog(level: .warning, "Rotated the Single Header token — update any app that still sends the old one.")
    }

    /// The coordinator only honors the token while Single Header is the
    /// selected sign-in method; switching modes revokes it immediately.
    private func syncConnectorHeaderToken() {
        guard let authCoordinator else { return }
        let token = connectorAuthMode == .singleHeaderToken ? connectorHeaderToken?.clientSecret : nil
        authCoordinator.updateStaticHeaderToken(token, clientName: "Single Header Client")
    }

    var connectorHeaderTokenJSON: String? {
        guard let token = connectorHeaderToken else { return nil }
        let payload = ["Authorization": "Bearer \(token.clientSecret)"]
        guard let data = try? JSONSerialization.data(withJSONObject: payload, options: [.prettyPrinted, .sortedKeys]) else {
            return nil
        }
        return String(data: data, encoding: .utf8)
    }

