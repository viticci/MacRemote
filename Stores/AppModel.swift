    private func tunnelReadinessCheck(publicMCPURL: URL?) -> ReadinessCheck {
        if let publicMCPURL {
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .ready,
                detail: publicMCPURL.absoluteString
            )
        }

        if case .downloading(let progress) = cloudflaredManager.state {
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .checking,
                detail: "Downloading Cloudflare's helper… \(Int((progress * 100).rounded()))%"
            )
        }
        if case .verifying = cloudflaredManager.state {
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .checking,
                detail: "Checking the download."
            )
        }
        // A helper that failed its check is a different problem from one that
        // was never installed, and saying "isn't installed" for it would be
        // untrue.
        if case .failed(let failure) = cloudflaredManager.state {
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .blocked,
                detail: failure.message
            )
        }

        switch tunnelStatus {
        case .unavailable:
            // Truthful: this is a real blocker, not a step the user simply
            // hasn't reached yet.
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .blocked,
                detail: "Cloudflare's helper isn't installed."
            )
        case .starting:
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .checking,
                detail: "Waiting for Cloudflare Tunnel."
            )
        case .reconnecting(let attempt):
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .checking,
                detail: "Reconnecting public link (attempt \(attempt))."
            )
        case .failed(let message):
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .blocked,
                detail: message
            )
        default:
            return ReadinessCheck(
                id: "public-tunnel",
                title: "Public MCP URL",
                status: .waiting,
                detail: serverStatus.isRunning
                    ? "Ready when you go public."
                    : "Ready after you start the server and go public."
            )
        }
    }

