    private func ensureLocalServerRunning() async -> URL? {
        if let localServerShutdownTask {
            await localServerShutdownTask.value
            self.localServerShutdownTask = nil
        }
        switch serverStatus {
        case .running(let url):
            return url
        case .starting:
            return nil
        case .stopped, .failed:
            break
        }

        if connectorAuthMode.requiresOAuthClientSecret, oauthClientCredentials.isEmpty {
            guard lockedOAuthClientIDs.isEmpty else {
                serverStatus = .failed("Your saved sign-in credentials are locked. Unlock them in Settings › Security, then start the server.")
                return nil
            }
            generateOAuthClientCredentials()
        }
        guard !connectorAuthMode.requiresOAuthClientSecret || !oauthClientCredentials.isEmpty else {
            serverStatus = .failed("Generate sign-in credentials in Settings › Security before starting the server.")
            return nil
        }
        if connectorAuthMode == .singleHeaderToken, connectorHeaderToken == nil {
            generateConnectorHeaderToken()
            syncConnectorHeaderToken()
        }

        serverStatus = .starting
        let accessReady = await refreshAccessStatusForServerStart()
        guard accessReady else {
            serverStatus = .failed("Required macOS access is missing for shared tools.")
            tunnelStatus = tunnelService.status(localServerURL: localServerURL)
            return nil
        }

        await startLocalServerAfterPermissionCheck()
        return localServerURL
    }

    private func startLocalServerAfterPermissionCheck() async {
        guard !serverStatus.isRunning else { return }
        let toolsToExpose = exposedTools
        guard !toolsToExpose.isEmpty else {
            serverStatus = .failed("Share at least one tool before starting the local server.")
            appendLog(level: .warning, "Blocked server start: no tools are currently shared.")
            return
        }

        do {
            toolSurfaceRuntime.update(tools: toolsToExpose)
            let runtime = toolSurfaceRuntime
            let tunnelService = tunnelService
            // UserDefaults is documented thread-safe; the server only reads it.
            nonisolated(unsafe) let userDefaults = userDefaults
            let server = LocalMCPServer(
                instanceID: instanceID,
                toolProvider: {
                    runtime.toolsSnapshot()
                },
                // The server serves the public link's host only while the
                // link is up; the tunnel is the one place that knows it.
                publicHost: {
                    tunnelService.publicHost()
                },
                resultCardPreferences: {
                    ResultCardPreferences(userDefaults: userDefaults)
                },
                authCoordinator: authCoordinator,
                toolCallApprovalCoordinator: toolCallApprovalCoordinator,
                toolExecutor: runtime,
                clientToolPermissionStore: clientToolPermissionStore,
                approvalDecisionLog: approvalDecisionLog,
                artifactStore: artifactStore
            ) { [weak self] event in
                Task { @MainActor in
                    self?.handleServerEvent(event)
                }
            }
            // A deployed Your Domain reaches this server only on the port it
            // was deployed with, so that port is asked for first.
            let deployedPort = savedCloudflareDomain?.localPort.flatMap { UInt16(exactly: $0) }
            let port = try server.start(preferredPort: deployedPort)
            let url = URL(string: "http://127.0.0.1:\(port)")!
            localServer = server
            localServerURL = url
            serverStatus = .running(url)
            tunnelStatus = tunnelService.status(localServerURL: url)
            appendLog(level: .info, "Local MCP server started on \(url.absoluteString).")
            if let deployedPort, deployedPort != port {
                appendLog(level: .warning, "Port \(deployedPort) is in use, so your domain must be deployed again before it can go public.")
            }
        } catch {
            let message = error.localizedDescription
            serverStatus = .failed(message)
            appendLog(level: .error, "Local MCP server failed to start: \(message)")
        }
    }

