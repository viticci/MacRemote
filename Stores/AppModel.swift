    /// Catalog refreshes are deliberately provenance-bound: only a tool with
    /// the preset's stable semantic ID can be updated. A hand-built tool with
    /// the same executable and arguments is equivalent for deduplication, but
    /// MacRemote never overwrites it. A complete first-party provider refresh
    /// may separately adopt one exact scan-provenance equivalent. Missing rows
    /// count as refresh work only after the selected scope has some installed
    /// representation; a completely fresh scope remains an Add operation.
    func catalogUpdateCount(in presets: [DefaultToolPreset] = DefaultToolPresetCatalog.presets) -> Int {
        let index = installationIndex
        let scanAdoptions = adoptableScannedTools(
            in: presets,
            installationIndex: index
        )
        let retiredIDs = retiredFedericoToolIDs(for: presets)
        let scopeIsAlreadyRepresented = index.installedCount(in: presets) > 0 ||
            !scanAdoptions.isEmpty ||
            !retiredIDs.isEmpty
        guard scopeIsAlreadyRepresented else { return 0 }
        return index.updateablePresets(in: presets).count
            + scanAdoptions.count
            + index.installablePresets(in: presets).count
            + retiredIDs.count
    }

