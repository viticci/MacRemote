    /// basename; the marker keeps later user-chosen categories authoritative.
    private func migrateStaleCatalogCategoriesIfNeeded() {
        guard !userDefaults.bool(forKey: Self.catalogCategoryMigrationKey) else { return }

        let presets = DefaultToolPresetCatalog.presets.map {
            CatalogCategoryReference(name: $0.name, executablePath: $0.executablePath, category: $0.category)
        }
        let updates = Self.staleCatalogCategoryUpdates(tools: tools, presets: presets)
        guard !updates.isEmpty else {
            userDefaults.set(true, forKey: Self.catalogCategoryMigrationKey)
            return
        }

        for index in tools.indices {
            if let category = updates[tools[index].id] {
                tools[index] = tools[index].withCategory(category)
            }
        }
        do {
            try persistUserDefinedTools()
            // Mark done only after a durable save; a failed write retries next launch.
            userDefaults.set(true, forKey: Self.catalogCategoryMigrationKey)
            appendLog(level: .info, "Updated the category of \(updates.count) tool\(updates.count == 1 ? "" : "s") to match the current library (e.g. AI & Agents).")
        } catch {
            appendLog(level: .error, "Could not save updated tool categories: \(error.localizedDescription)")
        }
    }

    /// Same shape as the category reconciliation: preset-derived tools carry
    /// random ids, so widget affordances added to catalog presets are copied
    /// onto matching persisted tools once (name + executable basename), and
    /// only when the tool has none — later user-authored actions stay theirs.
    private func migrateCatalogUIActionsIfNeeded() {
        guard !userDefaults.bool(forKey: Self.catalogUIActionsMigrationKey) else { return }

        var presetActions: [String: [ToolUIAction]] = [:]
        for preset in DefaultToolPresetCatalog.presets {
            guard let actions = preset.uiActions, !actions.isEmpty else { continue }
            presetActions[Self.categoryMigrationKey(name: preset.name, executablePath: preset.executablePath)] = actions
        }
        guard !presetActions.isEmpty else {
            userDefaults.set(true, forKey: Self.catalogUIActionsMigrationKey)
            return
        }

        var updated = 0
        for index in tools.indices where tools[index].origin == .userDefined && !tools[index].isMCPBridge {
            if tools[index].uiActions == nil {
                let key = Self.categoryMigrationKey(name: tools[index].name, executablePath: tools[index].executablePath)
                if let actions = presetActions[key] {
                    tools[index] = tools[index].withUIActions(actions)
                    updated += 1
                }
            } else if let repaired = Self.remCTLActionsWithRepairedJSONFlag(tools[index].uiActions ?? []) {
                tools[index] = tools[index].withUIActions(repaired)
                updated += 1
            }
        }
        guard updated > 0 else {
            userDefaults.set(true, forKey: Self.catalogUIActionsMigrationKey)
            return
        }
        do {
            try persistUserDefinedTools()
            // Mark done only after a durable save; a failed write retries next launch.
            userDefaults.set(true, forKey: Self.catalogUIActionsMigrationKey)
            appendLog(level: .info, "Added widget actions to \(updated) tool\(updated == 1 ? "" : "s") from the library catalog.")
        } catch {
            appendLog(level: .error, "Could not save widget actions: \(error.localizedDescription)")
        }
    }

    /// Pure core of the v3 repair: remctl parses `--json` per-subcommand,
    /// but earlier catalog actions emitted it as argv[0], where argparse
    /// exits 2 ("unrecognized arguments: --json") and every widget
    /// affordance — check-off, Reschedule, Edit Title, Delete — silently
    /// no-oped. Moves a leading "--json" to the end of the args array for
    /// remctl-targeted actions only; a different CLI that legitimately takes
    /// `--json` first must not be reordered. Returns nil when nothing
    /// needed repair.
    nonisolated static func remCTLActionsWithRepairedJSONFlag(_ actions: [ToolUIAction]) -> [ToolUIAction]? {
        var repairedAny = false
        let repaired = actions.map { action -> ToolUIAction in
            let targetsRemCTL = action.targetExecutableBasename == "remctl"
                || (action.toolID?.hasPrefix("remctl.") ?? false)
            guard targetsRemCTL,
                  case .object(var payload) = action.arguments,
                  case .array(var args) = payload["args"] ?? JSONValue.null,
                  args.first == .string("--json") else {
                return action
            }
            args.removeFirst()
            args.append(.string("--json"))
            payload["args"] = .array(args)
            repairedAny = true
            return ToolUIAction(
                id: action.id,
                title: action.title,
                kind: action.kind,
                toolID: action.toolID,
                targetExecutableBasename: action.targetExecutableBasename,
                arguments: .object(payload),
                requiredRowFields: action.requiredRowFields,
                completedWhenField: action.completedWhenField,
                completedWhenEquals: action.completedWhenEquals,
                style: action.style,
                inputs: action.inputs
            )
        }
        return repairedAny ? repaired : nil
    }

    struct CatalogCategoryReference: Sendable {
        let name: String
        let executablePath: String
        let category: ToolCategory
    }

    /// Pure core of the migration: tool id → corrected category, for
    /// user-defined tools whose name and executable basename exactly match a
    /// catalog preset that now lives in a different category.
    nonisolated static func staleCatalogCategoryUpdates(
        tools: [ToolDefinition],
        presets: [CatalogCategoryReference]
    ) -> [String: ToolCategory] {
        var presetCategories: [String: ToolCategory] = [:]
        for preset in presets {
            presetCategories[categoryMigrationKey(name: preset.name, executablePath: preset.executablePath)] = preset.category
        }

        var updates: [String: ToolCategory] = [:]
        for tool in tools where tool.origin == .userDefined && !tool.isMCPBridge {
            let key = categoryMigrationKey(name: tool.name, executablePath: tool.executablePath)
            if let category = presetCategories[key], tool.category != category {
                updates[tool.id] = category
            }
        }
        return updates
    }

    /// Match on the FULL executable path, not just the basename: a user's
    /// own Flexible Command named e.g. "Today" wrapping a *different* binary
    /// called "remctl" must never inherit a catalog tool's category or its
    /// (possibly destructive) widget actions. Preset-derived tools carry the
    /// catalog's exact resolved path, so legitimate retrofits still match.
    private nonisolated static func categoryMigrationKey(name: String, executablePath: String) -> String {
        "\(name)\u{1f}\(executablePath)"
    }

    private func appendTool(_ tool: ToolDefinition) {
        tools.append(tool)
        let canExposeImmediately = !serverStatus.isRunning ||
            !tool.permissionRequirements.contains(.fullDiskAccess) ||
            fullDiskAccessReport.isReady
        if canExposeImmediately {
            disabledToolIDs.remove(tool.id)
        } else {
            disabledToolIDs.insert(tool.id)
            presentFullDiskAccessPrompt(reason: .manualCheck)
        }
    }

    private func replaceLocalMCPBridgeTools(_ bridgeTools: [ToolDefinition], bridgeIdentity: String?) throws -> Int {
        guard let bridgeIdentity else {
            throw ToolValidationError.invalidMCPBridge("bridge identity is missing")
        }

        let originalTools = tools
        let originalDisabledToolIDs = disabledToolIDs
        let replacedToolIDs = tools
            .filter { $0.mcpBridgeIdentity == bridgeIdentity }
            .map(\.id)

        do {
            tools.removeAll { $0.mcpBridgeIdentity == bridgeIdentity }
            for toolID in replacedToolIDs {
                disabledToolIDs.remove(toolID)
                clientToolPermissionSnapshot = clientToolPermissionStore.removeToolIDFromAllClients(toolID)
            }
            for tool in bridgeTools {
                appendTool(tool)
            }

            try persistUserDefinedTools()
            persistToolExposureState()
            syncRunningToolSurface()
            return replacedToolIDs.count
        } catch {
            tools = originalTools
            disabledToolIDs = originalDisabledToolIDs
            throw error
        }
    }

    private static func toolSignature(_ tool: ToolDefinition) -> String {
        toolSignature(executablePath: tool.executablePath, argumentPattern: tool.argumentPattern)
