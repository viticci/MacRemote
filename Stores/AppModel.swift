/// What signing an app out actually removed (decision D45). Every field is a
/// measured count, and the sentence built from it omits whatever was zero — an
/// honest report beats a reassuring one.
struct ConnectedAppSignOutResult: Equatable, Sendable {
    let appName: String
    let registrations: Int
    let authorizations: Int
    let accessTokens: Int
    let refreshTokens: Int
    let pendingRequests: Int
    let alwaysAllowRules: Int

    var removedItemCount: Int {
        registrations + authorizations + accessTokens + refreshTokens
            + pendingRequests + alwaysAllowRules
    }

    /// "Signed out Claude — removed 1 registration, 2 access tokens, and 3
    /// Always Allow rules." Nothing that was zero appears.
    var summary: String {
        let clauses = [
            Self.clause(registrations, "registration", "registrations"),
            Self.clause(authorizations, "sign-in", "sign-ins"),
            Self.clause(accessTokens, "access token", "access tokens"),
            Self.clause(refreshTokens, "refresh token", "refresh tokens"),
            Self.clause(pendingRequests, "waiting request", "waiting requests"),
            Self.clause(alwaysAllowRules, "Always Allow rule", "Always Allow rules")
        ].compactMap { $0 }

        guard !clauses.isEmpty else {
            return "Signed out \(appName) — there was nothing left to remove."
        }
        return "Signed out \(appName) — removed \(Self.list(clauses))."
    }

    var logLine: String {
        "Signed out \(appName): \(registrations) registrations, \(authorizations) sign-ins, \(accessTokens) access tokens, \(refreshTokens) refresh tokens, \(pendingRequests) waiting requests, \(alwaysAllowRules) Always Allow rules."
    }

    private static func clause(_ count: Int, _ singular: String, _ plural: String) -> String? {
        guard count > 0 else { return nil }
        return "\(count) \(count == 1 ? singular : plural)"
    }

    private static func list(_ clauses: [String]) -> String {
        switch clauses.count {
        case 1: clauses[0]
        case 2: "\(clauses[0]) and \(clauses[1])"
        default: "\(clauses.dropLast().joined(separator: ", ")), and \(clauses[clauses.count - 1])"
        }
    }
}

extension ConnectedAppSignOutResult {
    /// The complete revocation set for one app, keyed only by client ID and
    /// OAuth trust ID. Display names are never used to select what to remove.
    /// Returns nil when the coordinator no longer knows the client.
    static func revoke(
        client: ConnectedClient,
        authCoordinator: OAuthCoordinator,
        toolCallApprovalCoordinator: ToolCallApprovalCoordinator?,
        permissionStore: ClientToolPermissionStore
    ) -> ConnectedAppSignOutResult? {
        guard let summary = authCoordinator.revokeClient(id: client.id) else {
            return nil
        }
        let deniedRequests = toolCallApprovalCoordinator?.denyPending(
            clientTrustID: client.trustID,
            clientID: client.id
        ) ?? 0
        let removedRules = permissionStore.removeClientTrustID(client.trustID).removedRules

        return ConnectedAppSignOutResult(
            appName: client.name,
            registrations: summary.clients,
            authorizations: summary.authorizations,
            accessTokens: summary.accessTokens,
            refreshTokens: summary.refreshTokens,
            pendingRequests: deniedRequests,
            alwaysAllowRules: removedRules
        )
    }
}

