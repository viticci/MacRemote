    func approveToolCallForever(_ id: UUID) {
        guard let request = toolCallApprovals.first(where: { $0.id == id }),
              let clientID = request.clientID,
              let clientTrustID = request.clientTrustID else {
            approveToolCallRequest(id)
            return
        }

        guard let currentTool = tool(id: request.toolID),
              currentTool.securityFingerprint == request.toolSecurityFingerprint else {
            _ = toolCallApprovalCoordinator.deny(requestID: id)
            appendLog(level: .warning, "The tool changed while approval was waiting. Review it and try again.")
            noteApprovalResolved()
            return
        }
        // Approve first: a request that already expired or was denied must not
        // leave a permanent rule behind.
        guard toolCallApprovalCoordinator.approve(requestID: id) else { return }
        setToolAlwaysAllowed(
            true,
            toolID: request.toolID,
            clientID: clientID,
            clientTrustID: clientTrustID
        )
        appendLog(level: .info, "\(request.clientName ?? "This app") can now run \(request.toolName) without asking.")
        noteApprovalResolved()
    }

